            WriteLine("else if (op != \":\")");
            WriteLine("{");
            Indent();
            WriteLine("_lastTokenWasColon = false;");
            Dedent();
            WriteLine("}");
            WriteLine("for (int i = 0; i < op.Length; i++) Advance();");
            WriteLine("return true;");
            Dedent();
            WriteLine("}");
            Dedent();
            WriteLine("}");
            WriteLine("return false;");
            Dedent();
            WriteLine("}");
            WriteLine();

            // Handle indentation for INDENT/DEDENT tokens
            WriteLine("private void HandleIndentation()");
            WriteLine("{");
            Indent();
            WriteLine("#if DEBUG_LOG");
            WriteLine("Console.WriteLine($\"[DEBUG] HandleIndentation: _atLineStart={_atLineStart}, position={_position}\");");
            WriteLine("#endif");
            WriteLine("if (!_atLineStart) return;");
            WriteLine("// Skip indentation processing inside parentheses");
            WriteLine("if (IsInsideParentheses)");
            WriteLine("{");
            Indent();
            WriteLine("#if DEBUG_LOG");
            WriteLine("Console.WriteLine(\"[DEBUG] Inside parentheses, setting _atLineStart=false\");");
            WriteLine("#endif");
            WriteLine("_atLineStart = false; // CRITICAL: Must set this to avoid infinite loop");
            WriteLine("return;");
            Dedent();
            WriteLine("}");
            WriteLine();
            WriteLine("// Calculate current line indentation");
            WriteLine("int indent = 0;");
            WriteLine("int indentStartColumn = _column; // Save start position for INDENT token");
            WriteLine("while (_position < _source.Length && (CurrentChar == ' ' || CurrentChar == '\\t'))");
            WriteLine("{");
            Indent();
            WriteLine("indent += (CurrentChar == '\\t' ? 8 : 1);");
            WriteLine("Advance();");
            Dedent();
            WriteLine("}");
            WriteLine();
            WriteLine("// CPython 3.12: Handle empty lines and comments for indentation");
            WriteLine("#if DEBUG_LOG");
            WriteLine("Console.WriteLine($\"[DEBUG] Checking empty line: position={_position}, length={_source.Length}, char='{CurrentChar}'\");");
            WriteLine("#endif");
            WriteLine("if (_position >= _source.Length || CurrentChar == '\\n' || CurrentChar == '#')");
            WriteLine("{");
            Indent();
            WriteLine("#if DEBUG_LOG");
            WriteLine("Console.WriteLine(\"[DEBUG] Empty line detected, setting _atLineStart=false\");");
            WriteLine("#endif");
            WriteLine("_atLineStart = false; // CRITICAL: Must set this to avoid infinite loop");
            WriteLine("// CPython 3.12: Don't process indentation for empty/comment lines");
            WriteLine("// DEDENT tokens will be generated when we encounter the next non-empty line");
            WriteLine("return;");
            Dedent();
            WriteLine("}");
            WriteLine();
            WriteLine("// Handle indentation changes");
            WriteLine("int currentLevel = _indentStack.Peek();");
            WriteLine("if (indent > currentLevel)");
            WriteLine("{");
            Indent();
            WriteLine("// Increased indentation - INDENT");
            WriteLine("// CPython 3.12: Only generate INDENT if we're actually increasing indentation");
            WriteLine("_indentStack.Push(indent);");
            WriteLine("var indentText = new string(' ', indent);");
            WriteLine("AddToken(GeneratedTokenType.INDENT, indentText, _line, indentStartColumn);");
            WriteLine("#if DEBUG_LOG");
            WriteLine("Console.WriteLine($\"[DEBUG] Generated INDENT token: level {currentLevel} -> {indent}\");");
            WriteLine("#endif");
            Dedent();
            WriteLine("}");
            WriteLine("else if (indent < currentLevel)");
            WriteLine("{");
            Indent();
            WriteLine("// Decreased indentation - DEDENT(s)");
            WriteLine("while (_indentStack.Count > 1 && _indentStack.Peek() > indent)");
            WriteLine("{");
            Indent();
            WriteLine("_indentStack.Pop();");
            WriteLine("// CPython 3.12: DEDENT position should point to current indentation level");
            WriteLine("// Use current position (start of current token) not previous position");
            WriteLine("_pendingTokens.Enqueue(new GeneratedTokenInfo(GeneratedTokenType.DEDENT, \"\", _line, indent));");
            Dedent();
            WriteLine("}");
            WriteLine();
            WriteLine("// Check for indentation error");
            WriteLine("if (_indentStack.Count > 0 && _indentStack.Peek() != indent)");
            WriteLine("{");
            Indent();
            WriteLine("throw new InvalidOperationException($\"IndentationError: unindent does not match any outer indentation level at line {_line}\");");
            Dedent();
            WriteLine("}");
            Dedent();
            WriteLine("}");
            WriteLine();
            WriteLine("#if DEBUG_LOG");
            WriteLine("Console.WriteLine(\"[DEBUG] Setting _atLineStart=false at end of HandleIndentation\");");
            WriteLine("#endif");
            WriteLine("_atLineStart = false;");
            WriteLine("// Now that we're starting to process this line, reset the line state for real token tracking");
            WriteLine("_currentLineHasRealTokens = false;");
            WriteLine("#if DEBUG_LOG");
            WriteLine("Console.WriteLine(\"[DEBUG] HandleIndentation method ending normally\");");
            WriteLine("#endif");
            Dedent();
            WriteLine("}");
            WriteLine();

            // Add IsStringPrefix method
            WriteLine("private bool IsStringPrefix()");
            WriteLine("{");
            Indent();
            WriteLine("// Check for string prefixes: r, b, rb, br, f, fr, rf");
            WriteLine("if (_position < _source.Length)");
            WriteLine("{");
            Indent();
            WriteLine("char c = char.ToLower(CurrentChar);");
            WriteLine("if (c == 'r' || c == 'b' || c == 'f')");
            WriteLine("{");
            Indent();
            WriteLine("// Check if followed by quote or another prefix");
            WriteLine("if (_position + 1 < _source.Length)");
            WriteLine("{");
            Indent();
            WriteLine("char next = _source[_position + 1];");
            WriteLine("if (next == '\\\"' || next == '\\'')");
            WriteLine("{");
            Indent();
            WriteLine("return true; // Single prefix like r\", b\", f\"");
            Dedent();
            WriteLine("}");
            WriteLine("else if (_position + 2 < _source.Length)");
            WriteLine("{");
            Indent();
            WriteLine("char next2 = char.ToLower(_source[_position + 1]);");
            WriteLine("char next3 = _source[_position + 2];");
            WriteLine("if ((c == 'r' && next2 == 'b') || (c == 'b' && next2 == 'r') || (c == 'f' && next2 == 'r') || (c == 'r' && next2 == 'f'))");
            WriteLine("{");
            Indent();
            WriteLine("if (next3 == '\\\"' || next3 == '\\'')");
            WriteLine("{");
            Indent();
            WriteLine("return true; // Double prefix like rb\", br\", fr\", rf\"");
            Dedent();
            WriteLine("}");
            Dedent();
            WriteLine("}");
            Dedent();
            WriteLine("}");
            Dedent();
            WriteLine("}");
            Dedent();
            WriteLine("}");
            Dedent();
            WriteLine("}");
            WriteLine("return false;");
            Dedent();
            WriteLine("}");
        }

        private string EscapeString(string value)
        {
            return value.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n").Replace("\r", "\\r").Replace("\t", "\\t");
        }

        // Output helper methods
        private void WriteLine(string line = "")
        {
            if (!string.IsNullOrEmpty(line))
            {
                _output.Append(new string(' ', _indentLevel * 4));
                _output.AppendLine(line);
            }
            else
            {
                _output.AppendLine();
            }
        }

        private void Indent() => _indentLevel++;
        private void Dedent() => _indentLevel--;
    }
