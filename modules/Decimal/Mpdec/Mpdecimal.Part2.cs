        /* Divide infinities. */
        private static void _mpd_qdiv_inf(mpd_t result, mpd_t a, mpd_t b, ref mpd_context_t ctx, ref uint status)
        {
            if (mpd_isinfinite(a))
            {
                if (mpd_isinfinite(b))
                {
                    mpd_seterror(result, MPD_Invalid_operation, ref status);
                    return;
                }
                mpd_setspecial(result, (byte)(mpd_sign(a) ^ mpd_sign(b)), MPD_INF);
                return;
            }
            Debug.Assert(mpd_isinfinite(b));
            _settriple(result, (byte)(mpd_sign(a) ^ mpd_sign(b)), 0, mpd_etiny(ref ctx));
            status |= MPD_Clamped;
        }

        // enum {NO_IDEAL_EXP, SET_IDEAL_EXP};
        private const int NO_IDEAL_EXP = 0;
        private const int SET_IDEAL_EXP = 1;

        /* Divide a by b. */
        private static void _mpd_qdiv(int action, mpd_t q, mpd_t a, mpd_t b, ref mpd_context_t ctx, ref uint status)
        {
            mpd_t aligned = MPD_NEW_STATIC(0, 0, 0, 0);
            ulong ld;
            long shift, exp, tz;
            long newsize;
            long ideal_exp;
            ulong rem;
            byte sign_a = mpd_sign(a);
            byte sign_b = mpd_sign(b);


            if (mpd_isspecial(a) || mpd_isspecial(b))
            {
                if (mpd_qcheck_nans(q, a, b, ref ctx, ref status))
                    return;
                _mpd_qdiv_inf(q, a, b, ref ctx, ref status);
                return;
            }
            if (mpd_iszerocoeff(b))
            {
                if (mpd_iszerocoeff(a))
                {
                    mpd_seterror(q, MPD_Division_undefined, ref status);
                }
                else
                {
                    mpd_setspecial(q, (byte)(sign_a ^ sign_b), MPD_INF);
                    status |= MPD_Division_by_zero;
                }
                return;
            }
            if (mpd_iszerocoeff(a))
            {
                exp = a.exp - b.exp;
                _settriple(q, (byte)(sign_a ^ sign_b), 0, exp);
                mpd_qfinalize(q, ref ctx, ref status);
                return;
            }

            shift = (b.digits - a.digits) + ctx.prec + 1;
            ideal_exp = a.exp - b.exp;
            exp = ideal_exp - shift;
            if (shift > 0)
            {
                if (!mpd_qshiftl(aligned, a, shift, ref status))
                {
                    mpd_seterror(q, MPD_Malloc_error, ref status);
                    goto finish;
                }
                a = aligned;
            }
            else if (shift < 0)
            {
                shift = -shift;
                if (!mpd_qshiftl(aligned, b, shift, ref status))
                {
                    mpd_seterror(q, MPD_Malloc_error, ref status);
                    goto finish;
                }
                b = aligned;
            }


            newsize = a.len - b.len + 1;
            if ((q != b && q != a) || (q == b && newsize > b.len))
            {
                if (!mpd_qresize(q, newsize, ref status))
                {
                    mpd_seterror(q, MPD_Malloc_error, ref status);
                    goto finish;
                }
            }


            if (b.len == 1)
            {
                rem = _mpd_shortdiv(q.data, a.data, (ulong)a.len, b.data[0]);
            }
            else if (b.len <= MPD_NEWTONDIV_CUTOFF)
            {
                // r == NULL: an empty span.
                int ret = _mpd_basedivmod(q.data, Span<ulong>.Empty, a.data, b.data, (ulong)a.len, (ulong)b.len);
                if (ret < 0)
                {
                    mpd_seterror(q, MPD_Malloc_error, ref status);
                    goto finish;
                }
                rem = (ulong)ret;
            }
            else
            {
                mpd_t r = MPD_NEW_STATIC(0, 0, 0, 0);
                _mpd_base_ndivmod(q, r, a, b, ref status);
                if (mpd_isspecial(q) || mpd_isspecial(r))
                {
                    mpd_setspecial(q, MPD_POS, MPD_NAN);
                    mpd_del(r);
                    goto finish;
                }
                rem = mpd_iszerocoeff(r) ? 0UL : 1UL;
                mpd_del(r);
                newsize = q.len;
            }

            newsize = _mpd_real_size(q.data, newsize);
            /* resize to smaller cannot fail */
            mpd_qresize(q, newsize, ref status);
            mpd_set_flags(q, (byte)(sign_a ^ sign_b));
            q.len = newsize;
            mpd_setdigits(q);

            shift = ideal_exp - exp;
            if (rem != 0)
            {
                ld = mpd_lsd(q.data[0]);
                if (ld == 0 || ld == 5)
                    q.data[0] += 1;
            }
            else if (action == SET_IDEAL_EXP && shift > 0)
            {
                tz = mpd_trail_zeros(q);
                shift = (tz > shift) ? shift : tz;
                mpd_qshiftr_inplace(q, shift);
                exp += shift;
            }

            q.exp = exp;


        finish:
            mpd_del(aligned);
            mpd_qfinalize(q, ref ctx, ref status);
        }

        /* Divide a by b. */
        public static void mpd_qdiv(mpd_t q, mpd_t a, mpd_t b, ref mpd_context_t ctx, ref uint status)
        {
            mpd_t aa = MPD_NEW_STATIC(0, 0, 0, 0);
            mpd_t bb = MPD_NEW_STATIC(0, 0, 0, 0);
            uint xstatus = 0;

            if (q == a)
            {
                if (!mpd_qcopy(aa, a, ref status))
                {
                    mpd_seterror(q, MPD_Malloc_error, ref status);
                    goto @out;
                }
                a = aa;
            }

            if (q == b)
            {
                if (!mpd_qcopy(bb, b, ref status))
                {
                    mpd_seterror(q, MPD_Malloc_error, ref status);
                    goto @out;
                }
                b = bb;
            }

            _mpd_qdiv(SET_IDEAL_EXP, q, a, b, ref ctx, ref xstatus);

            if ((xstatus & (MPD_Malloc_error | MPD_Division_impossible)) != 0)
            {
                /* Inexact quotients (the usual case) fill the entire context precision,
                 * which can lead to the above errors for very high precisions. Retry
                 * the operation with a lower precision in case the result is exact.
                 *
                 * We need an upper bound for the number of digits of a_coeff / b_coeff
                 * when the result is exact.  If a_coeff' * 1 / b_coeff' is in lowest
                 * terms, then maxdigits(a_coeff') + maxdigits(1 / b_coeff') is a suitable
                 * bound.
                 *
                 * 1 / b_coeff' is exact iff b_coeff' exclusively has prime factors 2 or 5.
                 * The largest amount of digits is generated if b_coeff' is a power of 2 or
                 * a power of 5 and is less than or equal to log5(b_coeff') <= log2(b_coeff').
                 *
                 * We arrive at a total upper bound:
                 *
                 *   maxdigits(a_coeff') + maxdigits(1 / b_coeff') <=
                 *   log10(a_coeff) + log2(b_coeff) =
                 *   log10(a_coeff) + log10(b_coeff) / log10(2) <=
                 *   a->digits + b->digits * 4;
                 */
                mpd_context_t workctx = ctx;
                uint ystatus = 0;

                workctx.prec = a.digits + b.digits * 4;
                if (workctx.prec >= ctx.prec)
                {
                    status |= (xstatus & MPD_Errors);
                    goto @out;  /* No point in retrying, keep the original error. */
                }

                _mpd_qdiv(SET_IDEAL_EXP, q, a, b, ref workctx, ref ystatus);
                if (ystatus != 0)
                {
                    ystatus = status | ((ystatus | xstatus) & MPD_Errors);
                    mpd_seterror(q, ystatus, ref status);
                }
            }
            else
            {
                status |= xstatus;
            }


        @out:
            mpd_del(aa);
            mpd_del(bb);
        }

        /* Internal function. */
        private static void _mpd_qdivmod(mpd_t q, mpd_t r, mpd_t a, mpd_t b, ref mpd_context_t ctx, ref uint status)
        {
            mpd_t aligned = MPD_NEW_STATIC(0, 0, 0, 0);
            long qsize, rsize;
            long ideal_exp, expdiff, shift;
            byte sign_a = mpd_sign(a);
            byte sign_ab = (byte)(mpd_sign(a) ^ mpd_sign(b));


            ideal_exp = (a.exp > b.exp) ? b.exp : a.exp;
            if (mpd_iszerocoeff(a))
            {
                if (!mpd_qcopy(r, a, ref status))
                    goto nanresult; /* GCOV_NOT_REACHED */
                r.exp = ideal_exp;
                _settriple(q, sign_ab, 0, 0);
                return;
            }

            expdiff = mpd_adjexp(a) - mpd_adjexp(b);
            if (expdiff < 0)
            {
                if (a.exp > b.exp)
                {
                    /* positive and less than b->digits - a->digits */
                    shift = a.exp - b.exp;
                    if (!mpd_qshiftl(r, a, shift, ref status))
                        goto nanresult;
                    r.exp = ideal_exp;
                }
                else
                {
                    if (!mpd_qcopy(r, a, ref status))
                        goto nanresult;
                }
                _settriple(q, sign_ab, 0, 0);
                return;
            }
            if (expdiff > ctx.prec)
            {
                status |= MPD_Division_impossible;
                goto nanresult;
            }


            /*
             * At this point we have:
             *   (1) 0 <= a->exp + a->digits - b->exp - b->digits <= prec
             *   (2) a->exp - b->exp >= b->digits - a->digits
             *   (3) a->exp - b->exp <= prec + b->digits - a->digits
             */
            if (a.exp != b.exp)
            {
                shift = a.exp - b.exp;
                if (shift > 0)
                {
                    /* by (3), after the shift a->digits <= prec + b->digits */
                    if (!mpd_qshiftl(aligned, a, shift, ref status))
                        goto nanresult;
                    a = aligned;
                }
                else
                {
                    shift = -shift;
                    /* by (2), after the shift b->digits <= a->digits */
                    if (!mpd_qshiftl(aligned, b, shift, ref status))
                        goto nanresult;
                    b = aligned;
                }
            }


            qsize = a.len - b.len + 1;
            if (!(q == a && qsize < a.len) && !(q == b && qsize < b.len))
            {
                if (!mpd_qresize(q, qsize, ref status))
                    goto nanresult;
            }

            rsize = b.len;
            if (!(r == a && rsize < a.len))
            {
                if (!mpd_qresize(r, rsize, ref status))
                    goto nanresult;
            }

            if (b.len == 1)
            {
                Debug.Assert(b.data[0] != 0); /* annotation for scan-build */
                if (a.len == 1)
                    _mpd_div_word(out q.data[0], out r.data[0], a.data[0], b.data[0]);
                else
                    r.data[0] = _mpd_shortdiv(q.data, a.data, (ulong)a.len, b.data[0]);
            }
            else if (b.len <= MPD_NEWTONDIV_CUTOFF)
            {
                int ret;
                ret = _mpd_basedivmod(q.data, r.data, a.data, b.data, (ulong)a.len, (ulong)b.len);
                if (ret == -1)
                {
                    status |= MPD_Malloc_error;
                    goto nanresult;
                }
            }
            else
            {
                _mpd_base_ndivmod(q, r, a, b, ref status);
                if (mpd_isspecial(q) || mpd_isspecial(r))
                    goto nanresult;
                qsize = q.len;
                rsize = r.len;
            }

            qsize = _mpd_real_size(q.data, qsize);
            /* resize to smaller cannot fail */
            mpd_qresize(q, qsize, ref status);
            q.len = qsize;
            mpd_setdigits(q);
            mpd_set_flags(q, sign_ab);
            q.exp = 0;
            if (q.digits > ctx.prec)
            {
                status |= MPD_Division_impossible;
                goto nanresult;
            }

            rsize = _mpd_real_size(r.data, rsize);
            /* resize to smaller cannot fail */
            mpd_qresize(r, rsize, ref status);
            r.len = rsize;
            mpd_setdigits(r);
            mpd_set_flags(r, sign_a);
            r.exp = ideal_exp;

        @out:
            mpd_del(aligned);
            return;

        nanresult:
            mpd_setspecial(q, MPD_POS, MPD_NAN);
            mpd_setspecial(r, MPD_POS, MPD_NAN);
            goto @out;
        }

        /* Integer division with remainder. */
        public static void mpd_qdivmod(mpd_t q, mpd_t r, mpd_t a, mpd_t b, ref mpd_context_t ctx, ref uint status)
        {
            byte sign = (byte)(mpd_sign(a) ^ mpd_sign(b));

            if (mpd_isspecial(a) || mpd_isspecial(b))
            {
                if (mpd_qcheck_nans(q, a, b, ref ctx, ref status))
                {
                    mpd_qcopy(r, q, ref status);
                    return;
                }
                if (mpd_isinfinite(a))
                {
                    if (mpd_isinfinite(b))
                        mpd_setspecial(q, MPD_POS, MPD_NAN);
                    else
                        mpd_setspecial(q, sign, MPD_INF);
                    mpd_setspecial(r, MPD_POS, MPD_NAN);
                    status |= MPD_Invalid_operation;
                    return;
                }
                if (mpd_isinfinite(b))
                {
                    if (!mpd_qcopy(r, a, ref status))
                    {
                        mpd_seterror(q, MPD_Malloc_error, ref status);
                        return;
                    }
                    mpd_qfinalize(r, ref ctx, ref status);
                    _settriple(q, sign, 0, 0);
                    return;
                }
                /* debug */
                throw mpd_err_fatal("mpd_qdivmod: unreachable"); /* GCOV_NOT_REACHED */
            }
            if (mpd_iszerocoeff(b))
            {
                if (mpd_iszerocoeff(a))
                {
                    mpd_setspecial(q, MPD_POS, MPD_NAN);
                    mpd_setspecial(r, MPD_POS, MPD_NAN);
                    status |= MPD_Division_undefined;
                }
                else
                {
                    mpd_setspecial(q, sign, MPD_INF);
                    mpd_setspecial(r, MPD_POS, MPD_NAN);
                    status |= (MPD_Division_by_zero | MPD_Invalid_operation);
                }
                return;
            }

            _mpd_qdivmod(q, r, a, b, ref ctx, ref status);
            mpd_qfinalize(q, ref ctx, ref status);
            mpd_qfinalize(r, ref ctx, ref status);
        }

        // mpd_qdivint
        public static void mpd_qdivint(mpd_t q, mpd_t a, mpd_t b, ref mpd_context_t ctx, ref uint status)
        {
            mpd_t r = MPD_NEW_STATIC(0, 0, 0, 0);
            byte sign = (byte)(mpd_sign(a) ^ mpd_sign(b));

            if (mpd_isspecial(a) || mpd_isspecial(b))
            {
                if (mpd_qcheck_nans(q, a, b, ref ctx, ref status))
                    return;
                if (mpd_isinfinite(a) && mpd_isinfinite(b))
                {
                    mpd_seterror(q, MPD_Invalid_operation, ref status);
                    return;
                }
                if (mpd_isinfinite(a))
                {
                    mpd_setspecial(q, sign, MPD_INF);
                    return;
                }
                if (mpd_isinfinite(b))
                {
                    _settriple(q, sign, 0, 0);
                    return;
                }
                /* debug */
                throw mpd_err_fatal("mpd_qdivint: unreachable"); /* GCOV_NOT_REACHED */
            }
            if (mpd_iszerocoeff(b))
            {
                if (mpd_iszerocoeff(a))
                {
                    mpd_seterror(q, MPD_Division_undefined, ref status);
                }
                else
                {
                    mpd_setspecial(q, sign, MPD_INF);
                    status |= MPD_Division_by_zero;
                }
                return;
            }


            _mpd_qdivmod(q, r, a, b, ref ctx, ref status);
            mpd_del(r);
            mpd_qfinalize(q, ref ctx, ref status);
        }

