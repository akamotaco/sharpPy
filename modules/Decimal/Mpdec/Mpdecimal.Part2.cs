        /*
         * Internal ln() function that does not check for specials, zero or one.
         * Relative error: abs(result - log(a)) < 0.1 * 10**-prec * abs(log(a))
         */
        private static void _mpd_qln(mpd_t result, mpd_t a, ref mpd_context_t ctx, ref uint status)
        {
            mpd_context_t varcontext = default, maxcontext = default;
            mpd_t z = result;
            mpd_t v = MPD_NEW_STATIC(0, 0, 0, 0);
            mpd_t vtmp = MPD_NEW_STATIC(0, 0, 0, 0);
            mpd_t tmp = MPD_NEW_STATIC(0, 0, 0, 0);
            long[] klist = new long[MPD_MAX_PREC_LOG2];
            long maxprec, shift, t;
            long a_digits, a_exp;
            ulong dummy, x;
            int i;

            Debug.Assert(!mpd_isspecial(a) && !mpd_iszerocoeff(a));

            /*
             * We are calculating ln(a) = ln(v * 10^t) = ln(v) + t*ln(10),
             * where 0.5 < v <= 5.
             */
            if (!mpd_qcopy(v, a, ref status))
            {
                mpd_seterror(result, MPD_Malloc_error, ref status);
                goto finish;
            }

            /* Initial approximation: we have at least one non-zero digit */
            _mpd_get_msdigits(out dummy, out x, v, 3);
            if (x < 10) x *= 10;
            if (x < 100) x *= 10;
            x -= 100;

            /* a may equal z */
            a_digits = a.digits;
            a_exp = a.exp;

            mpd_minalloc(z);
            mpd_clear_flags(z);
            z.data[0] = lnapprox[x];
            z.len = 1;
            z.exp = -3;
            mpd_setdigits(z);

            if (x <= 400)
            {
                /* Reduce the input operand to 1.00 <= v <= 5.00. Let y = x + 100,
                 * so 100 <= y <= 500. Since y contains the most significant digits
                 * of v, y/100 <= v < (y+1)/100 and abs(z - log(v)) < 10**-2. */
                v.exp = -(a_digits - 1);
                t = a_exp + a_digits - 1;
            }
            else
            {
                /* Reduce the input operand to 0.500 < v <= 0.999. Let y = x + 100,
                 * so 500 < y <= 999. Since y contains the most significant digits
                 * of v, y/1000 <= v < (y+1)/1000 and abs(z - log(v)) < 10**-2. */
                v.exp = -a_digits;
                t = a_exp + a_digits;
                mpd_set_negative(z);
            }

            mpd_maxcontext(ref maxcontext);
            mpd_maxcontext(ref varcontext);
            varcontext.round = MPD_ROUND_TRUNC;

            maxprec = ctx.prec + 2;
            if (t == 0 && (x <= 15 || x >= 800))
            {
                /* 0.900 <= v <= 1.15: Estimate the magnitude of the logarithm.
                 * If ln(v) will underflow, skip the loop. Otherwise, adjust the
                 * precision upwards in order to obtain a sufficient number of
                 * significant digits.
                 *
                 *   Case v > 1:
                 *      abs((v-1)/10) < abs((v-1)/v) < abs(ln(v)) < abs(v-1)
                 *   Case v < 1:
                 *      abs(v-1) < abs(ln(v)) < abs((v-1)/v) < abs((v-1)*10)
                 */
                int cmp = _mpd_cmp(v, one);

                /* Upper bound (assume v > 1): abs(v-1), unrounded */
                _mpd_qsub(tmp, v, one, ref maxcontext, ref maxcontext.status);
                if ((maxcontext.status & MPD_Errors) != 0)
                {
                    mpd_seterror(result, MPD_Malloc_error, ref status);
                    goto finish;
                }

                if (cmp < 0)
                {
                    /* v < 1: abs((v-1)*10) */
                    tmp.exp += 1;
                }
                if (mpd_adjexp(tmp) < mpd_etiny(ref ctx))
                {
                    /* The upper bound is less than etiny: Underflow to zero */
                    _settriple(result, (byte)(cmp < 0 ? 1 : 0), 1, mpd_etiny(ref ctx) - 1);
                    goto finish;
                }
                /* Lower bound: abs((v-1)/10) or abs(v-1) */
                tmp.exp -= 1;
                if (mpd_adjexp(tmp) < 0)
                {
                    /* Absolute error of the loop: abs(z - log(v)) < 10**-p. If
                     * p = ctx->prec+2-adjexp(lower), then the relative error of
                     * the result is (using 10**adjexp(x) <= abs(x)):
                     *
                     *   abs(z - log(v)) / abs(log(v)) < 10**-p / abs(log(v))
                     *                                 <= 10**(-ctx->prec-2)
                     */
                    maxprec = maxprec - mpd_adjexp(tmp);
                }
            }

            i = ln_schedule_prec(klist, maxprec, 2);
            for (; i >= 0; i--)
            {
                varcontext.prec = 2 * klist[i] + 3;
                z.flags ^= MPD_NEG;
                _mpd_qexp(tmp, z, ref varcontext, ref status);
                z.flags ^= MPD_NEG;

                if (v.digits > varcontext.prec)
                {
                    shift = v.digits - varcontext.prec;
                    mpd_qshiftr(vtmp, v, shift, ref status);
                    vtmp.exp += shift;
                    mpd_qmul(tmp, vtmp, tmp, ref varcontext, ref status);
                }
                else
                {
                    mpd_qmul(tmp, v, tmp, ref varcontext, ref status);
                }

                mpd_qsub(tmp, tmp, one, ref maxcontext, ref status);
                mpd_qadd(z, z, tmp, ref maxcontext, ref status);
                if (mpd_isspecial(z))
                    break;
            }

            /*
             * Case t == 0:
             *    t * log(10) == 0, the result does not change and the analysis
             *    above applies. If v < 0.900 or v > 1.15, the relative error is
             *    less than 10**(-ctx.prec-1).
             * Case t != 0:
             *      z := approx(log(v))
             *      y := approx(log(10))
             *      p := maxprec = ctx->prec + 2
             *   Absolute errors:
             *      1) abs(z - log(v)) < 10**-p
             *      2) abs(y - log(10)) < 10**-p
             *   The multiplication is exact, so:
             *      3) abs(t*y - t*log(10)) < t*10**-p
             *   The sum is exact, so:
             *      4) abs((z + t*y) - (log(v) + t*log(10))) < (abs(t) + 1) * 10**-p
             *   Bounds for log(v) and log(10):
             *      5) -7/10 < log(v) < 17/10
             *      6) 23/10 < log(10) < 24/10
             *   Using 4), 5), 6) and t != 0, the relative error is:
             *
             *      7) relerr < ((abs(t) + 1)*10**-p) / abs(log(v) + t*log(10))
             *                < 0.5 * 10**(-p + 1) = 0.5 * 10**(-ctx->prec-1)
             */
            mpd_qln10(v, maxprec + 1, ref status);
            mpd_qmul_ssize(tmp, v, t, ref maxcontext, ref status);
            mpd_qadd(result, tmp, z, ref maxcontext, ref status);


        finish:
            status |= (MPD_Inexact | MPD_Rounded);
            mpd_del(v);
            mpd_del(vtmp);
            mpd_del(tmp);
        }

        /* ln(a) */
        public static void mpd_qln(mpd_t result, mpd_t a, ref mpd_context_t ctx, ref uint status)
        {
            mpd_context_t workctx;
            long adjexp, t;

            if (mpd_isspecial(a))
            {
                if (mpd_qcheck_nan(result, a, ref ctx, ref status))
                    return;
                if (mpd_isnegative(a))
                {
                    mpd_seterror(result, MPD_Invalid_operation, ref status);
                    return;
                }
                mpd_setspecial(result, MPD_POS, MPD_INF);
                return;
            }
            if (mpd_iszerocoeff(a))
            {
                mpd_setspecial(result, MPD_NEG, MPD_INF);
                return;
            }
            if (mpd_isnegative(a))
            {
                mpd_seterror(result, MPD_Invalid_operation, ref status);
                return;
            }
            if (_mpd_cmp(a, one) == 0)
            {
                _settriple(result, MPD_POS, 0, 0);
                return;
            }
            /*
             * Check if the result will overflow (0 < x, x != 1):
             *   1) log10(x) < 0 iff adjexp(x) < 0
             *   2) 0 < x /\ x <= y ==> adjexp(x) <= adjexp(y)
             *   3) 0 < x /\ x != 1 ==> 2 * abs(log10(x)) < abs(log(x))
             *   4) adjexp(x) <= log10(x) < adjexp(x) + 1
             *
             * Case adjexp(x) >= 0:
             *   5) 2 * adjexp(x) < abs(log(x))
             *   Case adjexp(x) > 0:
             *     6) adjexp(2 * adjexp(x)) <= adjexp(abs(log(x)))
             *   Case adjexp(x) == 0:
             *     mpd_exp_digits(t)-1 == 0 <= emax (the shortcut is not triggered)
             *
             * Case adjexp(x) < 0:
             *   7) 2 * (-adjexp(x) - 1) < abs(log(x))
             *   Case adjexp(x) < -1:
             *     8) adjexp(2 * (-adjexp(x) - 1)) <= adjexp(abs(log(x)))
             *   Case adjexp(x) == -1:
             *     mpd_exp_digits(t)-1 == 0 <= emax (the shortcut is not triggered)
             */
            adjexp = mpd_adjexp(a);
            t = (adjexp < 0) ? -adjexp - 1 : adjexp;
            t *= 2;
            if (mpd_exp_digits(t) - 1 > ctx.emax)
            {
                status |= MPD_Overflow | MPD_Inexact | MPD_Rounded;
                mpd_setspecial(result, (byte)(adjexp < 0 ? 1 : 0), MPD_INF);
                return;
            }

            workctx = ctx;
            workctx.round = MPD_ROUND_HALF_EVEN;

            if (ctx.allcr != 0)
            {
                mpd_t t1 = MPD_NEW_STATIC(0, 0, 0, 0);
                mpd_t t2 = MPD_NEW_STATIC(0, 0, 0, 0);
                mpd_t ulp = MPD_NEW_STATIC(0, 0, 0, 0);
                mpd_t aa = MPD_NEW_STATIC(0, 0, 0, 0);
                long prec;

                if (result == a)
                {
                    if (!mpd_qcopy(aa, a, ref status))
                    {
                        mpd_seterror(result, MPD_Malloc_error, ref status);
                        return;
                    }
                    a = aa;
                }

                workctx.clamp = 0;
                prec = ctx.prec + 3;
                while (true)
                {
                    workctx.prec = prec;
                    _mpd_qln(result, a, ref workctx, ref status);
                    _ssettriple(ulp, MPD_POS, 1,
                                result.exp + result.digits - workctx.prec);

                    workctx.prec = ctx.prec;
                    mpd_qadd(t1, result, ulp, ref workctx, ref workctx.status);
                    mpd_qsub(t2, result, ulp, ref workctx, ref workctx.status);
                    if (mpd_isspecial(result) || mpd_iszerocoeff(result) ||
                        mpd_qcmp(t1, t2, ref status) == 0)
                    {
                        workctx.clamp = ctx.clamp;
                        mpd_check_underflow(result, ref workctx, ref status);
                        mpd_qfinalize(result, ref workctx, ref status);
                        break;
                    }
                    prec += MPD_RDIGITS;
                }
                mpd_del(t1);
                mpd_del(t2);
                mpd_del(ulp);
                mpd_del(aa);
            }
            else
            {
                _mpd_qln(result, a, ref workctx, ref status);
                mpd_check_underflow(result, ref workctx, ref status);
                mpd_qfinalize(result, ref workctx, ref status);
            }
        }

        /*
         * Internal log10() function that does not check for specials, zero or one.
         * Case SKIP_FINALIZE:
         *   Relative error: abs(result - log10(a)) < 0.1 * 10**-prec * abs(log10(a))
         * Case DO_FINALIZE:
         *   Ulp error: abs(result - log10(a)) < ulp(log10(a))
         */
        // enum {SKIP_FINALIZE, DO_FINALIZE};
        private const int SKIP_FINALIZE = 0;
        private const int DO_FINALIZE = 1;

        // _mpd_qlog10
        private static void _mpd_qlog10(int action, mpd_t result, mpd_t a, ref mpd_context_t ctx, ref uint status)
        {
            mpd_context_t workctx = default;
            mpd_t ln10 = MPD_NEW_STATIC(0, 0, 0, 0);

            mpd_maxcontext(ref workctx);
            workctx.prec = ctx.prec + 3;
            /* relative error: 0.1 * 10**(-p-3). The specific underflow shortcut
             * in _mpd_qln() does not change the final result. */
            _mpd_qln(result, a, ref workctx, ref status);
            /* relative error: 5 * 10**(-p-3) */
            mpd_qln10(ln10, workctx.prec, ref status);

            if (action == DO_FINALIZE)
            {
                workctx = ctx;
                workctx.round = MPD_ROUND_HALF_EVEN;
            }
            /* SKIP_FINALIZE: relative error: 5 * 10**(-p-3) */
            _mpd_qdiv(NO_IDEAL_EXP, result, result, ln10, ref workctx, ref status);

            mpd_del(ln10);
        }

        /* log10(a) */
        public static void mpd_qlog10(mpd_t result, mpd_t a, ref mpd_context_t ctx, ref uint status)
        {
            mpd_context_t workctx;
            long adjexp, t;

            workctx = ctx;
            workctx.round = MPD_ROUND_HALF_EVEN;

            if (mpd_isspecial(a))
            {
                if (mpd_qcheck_nan(result, a, ref ctx, ref status))
                    return;
                if (mpd_isnegative(a))
                {
                    mpd_seterror(result, MPD_Invalid_operation, ref status);
                    return;
                }
                mpd_setspecial(result, MPD_POS, MPD_INF);
                return;
            }
            if (mpd_iszerocoeff(a))
            {
                mpd_setspecial(result, MPD_NEG, MPD_INF);
                return;
            }
            if (mpd_isnegative(a))
            {
                mpd_seterror(result, MPD_Invalid_operation, ref status);
                return;
            }
            if (mpd_coeff_ispow10(a))
            {
                byte sign = 0;
                adjexp = mpd_adjexp(a);
                if (adjexp < 0)
                {
                    sign = 1;
                    adjexp = -adjexp;
                }
                _settriple(result, sign, (ulong)adjexp, 0);
                mpd_qfinalize(result, ref workctx, ref status);
                return;
            }
            /*
             * Check if the result will overflow (0 < x, x != 1):
             *   1) log10(x) < 0 iff adjexp(x) < 0
             *   2) 0 < x /\ x <= y ==> adjexp(x) <= adjexp(y)
             *   3) adjexp(x) <= log10(x) < adjexp(x) + 1
             *
             * Case adjexp(x) >= 0:
             *   4) adjexp(x) <= abs(log10(x))
             *   Case adjexp(x) > 0:
             *     5) adjexp(adjexp(x)) <= adjexp(abs(log10(x)))
             *   Case adjexp(x) == 0:
             *     mpd_exp_digits(t)-1 == 0 <= emax (the shortcut is not triggered)
             *
             * Case adjexp(x) < 0:
             *   6) -adjexp(x) - 1 < abs(log10(x))
             *   Case adjexp(x) < -1:
             *     7) adjexp(-adjexp(x) - 1) <= adjexp(abs(log(x)))
             *   Case adjexp(x) == -1:
             *     mpd_exp_digits(t)-1 == 0 <= emax (the shortcut is not triggered)
             */
            adjexp = mpd_adjexp(a);
            t = (adjexp < 0) ? -adjexp - 1 : adjexp;
            if (mpd_exp_digits(t) - 1 > ctx.emax)
            {
                status |= MPD_Overflow | MPD_Inexact | MPD_Rounded;
                mpd_setspecial(result, (byte)(adjexp < 0 ? 1 : 0), MPD_INF);
                return;
            }

            if (ctx.allcr != 0)
            {
                mpd_t t1 = MPD_NEW_STATIC(0, 0, 0, 0);
                mpd_t t2 = MPD_NEW_STATIC(0, 0, 0, 0);
                mpd_t ulp = MPD_NEW_STATIC(0, 0, 0, 0);
                mpd_t aa = MPD_NEW_STATIC(0, 0, 0, 0);
                long prec;

                if (result == a)
                {
                    if (!mpd_qcopy(aa, a, ref status))
                    {
                        mpd_seterror(result, MPD_Malloc_error, ref status);
                        return;
                    }
                    a = aa;
                }

                workctx.clamp = 0;
                prec = ctx.prec + 3;
                while (true)
                {
                    workctx.prec = prec;
                    _mpd_qlog10(SKIP_FINALIZE, result, a, ref workctx, ref status);
                    _ssettriple(ulp, MPD_POS, 1,
                                result.exp + result.digits - workctx.prec);

                    workctx.prec = ctx.prec;
                    mpd_qadd(t1, result, ulp, ref workctx, ref workctx.status);
                    mpd_qsub(t2, result, ulp, ref workctx, ref workctx.status);
                    if (mpd_isspecial(result) || mpd_iszerocoeff(result) ||
                        mpd_qcmp(t1, t2, ref status) == 0)
                    {
                        workctx.clamp = ctx.clamp;
                        mpd_check_underflow(result, ref workctx, ref status);
                        mpd_qfinalize(result, ref workctx, ref status);
                        break;
                    }
                    prec += MPD_RDIGITS;
                }
                mpd_del(t1);
                mpd_del(t2);
                mpd_del(ulp);
                mpd_del(aa);
            }
            else
            {
                _mpd_qlog10(DO_FINALIZE, result, a, ref workctx, ref status);
                mpd_check_underflow(result, ref workctx, ref status);
            }
        }

        /*
         * Maximum of the two operands. Attention: If one operand is a quiet NaN and the
         * other is numeric, the numeric operand is returned. This may not be what one
         * expects.
         */
        public static void mpd_qmax(mpd_t result, mpd_t a, mpd_t b, ref mpd_context_t ctx, ref uint status)
        {
            int c;

            if (mpd_isqnan(a) && !mpd_isnan(b))
            {
                mpd_qcopy(result, b, ref status);
            }
            else if (mpd_isqnan(b) && !mpd_isnan(a))
            {
                mpd_qcopy(result, a, ref status);
            }
            else if (mpd_qcheck_nans(result, a, b, ref ctx, ref status))
            {
                return;
            }
            else
            {
                c = _mpd_cmp(a, b);
                if (c == 0)
                    c = _mpd_cmp_numequal(a, b);

                if (c < 0)
                    mpd_qcopy(result, b, ref status);
                else
                    mpd_qcopy(result, a, ref status);
            }

            mpd_qfinalize(result, ref ctx, ref status);
        }

