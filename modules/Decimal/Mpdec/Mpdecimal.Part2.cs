         * Set 'result' to log(10).
         *   Ulp error: abs(result - log(10)) < ulp(log(10))
         *   Relative error: abs(result - log(10)) < 5 * 10**-prec * log(10)
         *
         * NOTE: The relative error is not derived from the ulp error, but
         * calculated separately using the fact that 23/10 < log(10) < 24/10.
         */
        public static void mpd_qln10(mpd_t result, long prec, ref uint status)
        {
            mpd_context_t varcontext = default, maxcontext = default;
            mpd_t tmp = MPD_NEW_STATIC(0, 0, 0, 0);
            mpd_t static10 = MPD_NEW_CONST(0, 0, 2, 1, 1, 10);
            long[] klist = new long[MPD_MAX_PREC_LOG2];
            ulong rnd;
            long shift;
