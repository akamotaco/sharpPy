        /*
         * The absolute value of a. If a is negative, the result is the same
         * as the result of the minus operation. Otherwise, the result is the
         * result of the plus operation.
         */
        public static void mpd_qabs(mpd_t result, mpd_t a, ref mpd_context_t ctx, ref uint status)
        {
            if (mpd_isspecial(a))
            {
                if (mpd_qcheck_nan(result, a, ref ctx, ref status))
                    return;
            }

            if (mpd_isnegative(a))
                mpd_qminus(result, a, ref ctx, ref status);
            else
                mpd_qplus(result, a, ref ctx, ref status);
        }

        // _mpd_ptrswap
        private static void _mpd_ptrswap(ref mpd_t a, ref mpd_t b)
        {
            mpd_t t = a;
            a = b;
            b = t;
        }

        /* Add or subtract infinities. */
        private static void _mpd_qaddsub_inf(mpd_t result, mpd_t a, mpd_t b, byte sign_b, ref uint status)
        {
            if (mpd_isinfinite(a))
            {
                if (mpd_sign(a) != sign_b && mpd_isinfinite(b))
                    mpd_seterror(result, MPD_Invalid_operation, ref status);
                else
                    mpd_setspecial(result, mpd_sign(a), MPD_INF);
                return;
            }
            Debug.Assert(mpd_isinfinite(b));
            mpd_setspecial(result, sign_b, MPD_INF);
        }

        /* Add or subtract non-special numbers. */
        private static void _mpd_qaddsub(mpd_t result, mpd_t a, mpd_t b, byte sign_b, ref mpd_context_t ctx, ref uint status)
        {
            mpd_t big, small;
            mpd_t big_aligned = MPD_NEW_STATIC(0, 0, 0, 0);
            mpd_t tiny = MPD_NEW_CONST(0, 0, 1, 1, 1, 1);
            ulong carry;
            long newsize, shift;
            long exp, i;
            int swap = 0;


            /* compare exponents */
            big = a; small = b;
            if (big.exp != small.exp)
            {
                if (small.exp > big.exp)
                {
                    _mpd_ptrswap(ref big, ref small);
                    swap++;
                }
                /* align the coefficients */
                if (!mpd_iszerocoeff(big))
                {
                    exp = big.exp - 1;
                    exp += (big.digits > ctx.prec) ? 0 : big.digits - ctx.prec - 1;
                    if (mpd_adjexp(small) < exp)
                    {
                        /*
                         * Avoid huge shifts by substituting a value for small that is
                         * guaranteed to produce the same results.
                         *
                         * adjexp(small) < exp if and only if:
                         *
                         *   bdigits <= prec AND
                         *   bdigits+shift >= prec+2+sdigits AND
                         *   exp = bexp+bdigits-prec-2
                         *
                         *     1234567000000000  ->  bdigits + shift
                         *     ----------XX1234  ->  sdigits
                         *     ----------X1      ->  tiny-digits
                         *     |- prec -|
                         *
                         *      OR
                         *
                         *   bdigits > prec AND
                         *   shift > sdigits AND
                         *   exp = bexp-1
                         *
                         *     1234567892100000  ->  bdigits + shift
                         *     ----------XX1234  ->  sdigits
                         *     ----------X1      ->  tiny-digits
                         *     |- prec -|
                         *
                         * If tiny is zero, adding or subtracting is a no-op.
                         * Otherwise, adding tiny generates a non-zero digit either
                         * below the rounding digit or the least significant digit
                         * of big. When subtracting, tiny is in the same position as
                         * the carry that would be generated by subtracting sdigits.
                         */
                        mpd_copy_flags(tiny, small);
                        tiny.exp = exp;
                        tiny.digits = 1;
                        tiny.len = 1;
                        tiny.data[0] = mpd_iszerocoeff(small) ? 0UL : 1UL;
                        small = tiny;
                    }
                    /* This cannot wrap: the difference is positive and <= maxprec */
                    shift = big.exp - small.exp;
                    if (!mpd_qshiftl(big_aligned, big, shift, ref status))
                    {
                        mpd_seterror(result, MPD_Malloc_error, ref status);
                        goto finish;
                    }
                    big = big_aligned;
                }
            }
            result.exp = small.exp;


            /* compare length of coefficients */
            if (big.len < small.len)
            {
                _mpd_ptrswap(ref big, ref small);
                swap++;
            }

            newsize = big.len;
            if (!mpd_qresize(result, newsize, ref status))
                goto finish;

            if (mpd_sign(a) == sign_b)
            {

                carry = _mpd_baseadd(result.data, big.data, small.data, (ulong)big.len, (ulong)small.len);

                if (carry != 0)
                {
                    newsize = big.len + 1;
                    if (!mpd_qresize(result, newsize, ref status))
                        goto finish;
                    result.data[newsize - 1] = carry;
                }

                result.len = newsize;
                mpd_set_flags(result, sign_b);
            }
            else
            {
                if (big.len == small.len)
                {
                    for (i = big.len - 1; i >= 0; --i)
                    {
                        if (big.data[i] != small.data[i])
                        {
                            if (big.data[i] < small.data[i])
                            {
                                _mpd_ptrswap(ref big, ref small);
                                swap++;
                            }
                            break;
                        }
                    }
                }

                _mpd_basesub(result.data, big.data, small.data, (ulong)big.len, (ulong)small.len);
                newsize = _mpd_real_size(result.data, big.len);
                /* resize to smaller cannot fail */
                mpd_qresize(result, newsize, ref status);

                result.len = newsize;
                sign_b = (swap & 1) != 0 ? sign_b : mpd_sign(a);
                mpd_set_flags(result, sign_b);

                if (mpd_iszerocoeff(result))
                {
                    mpd_set_positive(result);
                    if (ctx.round == MPD_ROUND_FLOOR)
                        mpd_set_negative(result);
                }
            }

            mpd_setdigits(result);

        finish:
            mpd_del(big_aligned);
        }

        /* Add a and b. No specials, no finalizing. */
        private static void _mpd_qadd(mpd_t result, mpd_t a, mpd_t b, ref mpd_context_t ctx, ref uint status)
        {
            _mpd_qaddsub(result, a, b, mpd_sign(b), ref ctx, ref status);
        }

        /* Subtract b from a. No specials, no finalizing. */
        private static void _mpd_qsub(mpd_t result, mpd_t a, mpd_t b, ref mpd_context_t ctx, ref uint status)
        {
            _mpd_qaddsub(result, a, b, (byte)(mpd_sign(b) == 0 ? 1 : 0), ref ctx, ref status);
        }

        /* Add a and b. */
        public static void mpd_qadd(mpd_t result, mpd_t a, mpd_t b, ref mpd_context_t ctx, ref uint status)
        {
            if (mpd_isspecial(a) || mpd_isspecial(b))
            {
                if (mpd_qcheck_nans(result, a, b, ref ctx, ref status))
                    return;
                _mpd_qaddsub_inf(result, a, b, mpd_sign(b), ref status);
                return;
            }

            _mpd_qaddsub(result, a, b, mpd_sign(b), ref ctx, ref status);
            mpd_qfinalize(result, ref ctx, ref status);
        }

        /* Add a and b. Set NaN/Invalid_operation if the result is inexact. */
        private static void _mpd_qadd_exact(mpd_t result, mpd_t a, mpd_t b, ref mpd_context_t ctx, ref uint status)
        {
            uint workstatus = 0;

            mpd_qadd(result, a, b, ref ctx, ref workstatus);
            status |= workstatus;
            if ((workstatus & (MPD_Inexact | MPD_Rounded | MPD_Clamped)) != 0)
                mpd_seterror(result, MPD_Invalid_operation, ref status);
        }

        /* Subtract b from a. */
        public static void mpd_qsub(mpd_t result, mpd_t a, mpd_t b, ref mpd_context_t ctx, ref uint status)
        {
            if (mpd_isspecial(a) || mpd_isspecial(b))
            {
                if (mpd_qcheck_nans(result, a, b, ref ctx, ref status))
                    return;
                _mpd_qaddsub_inf(result, a, b, (byte)(mpd_sign(b) == 0 ? 1 : 0), ref status);
                return;
            }

            _mpd_qaddsub(result, a, b, (byte)(mpd_sign(b) == 0 ? 1 : 0), ref ctx, ref status);
            mpd_qfinalize(result, ref ctx, ref status);
        }

        /* Subtract b from a. Set NaN/Invalid_operation if the result is inexact. */
        private static void _mpd_qsub_exact(mpd_t result, mpd_t a, mpd_t b, ref mpd_context_t ctx, ref uint status)
        {
