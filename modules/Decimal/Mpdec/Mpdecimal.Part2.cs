            result.exp = -(result.digits - 1);

            mpd_maxcontext(ref maxcontext);
            if (prec < MPD_MINALLOC_MAX * MPD_RDIGITS)
            {
                maxcontext.prec = prec;
                _mpd_apply_round_excess(result, rnd, ref maxcontext, ref status);
                status |= (MPD_Inexact | MPD_Rounded);
                return;
            }

            mpd_maxcontext(ref varcontext);
            varcontext.round = MPD_ROUND_TRUNC;

            i = ln_schedule_prec(klist, prec + 2, -result.exp);
            for (; i >= 0; i--)
            {
                varcontext.prec = 2 * klist[i] + 3;
                result.flags ^= MPD_NEG;
                _mpd_qexp(tmp, result, ref varcontext, ref status);
                result.flags ^= MPD_NEG;
                mpd_qmul(tmp, static10, tmp, ref varcontext, ref status);
                mpd_qsub(tmp, tmp, one, ref maxcontext, ref status);
                mpd_qadd(result, result, tmp, ref maxcontext, ref status);
                if (mpd_isspecial(result))
                    break;
            }

            mpd_del(tmp);
            maxcontext.prec = prec;
            mpd_qfinalize(result, ref maxcontext, ref status);
        }

