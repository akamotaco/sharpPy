        /* Pad the result with trailing zeros if it has fewer digits than prec. */
        private static void _mpd_zeropad(mpd_t result, ref mpd_context_t ctx, ref uint status)
        {
            if (!mpd_isspecial(result) && !mpd_iszero(result) &&
                result.digits < ctx.prec)
            {
                long shift = ctx.prec - result.digits;
                mpd_qshiftl(result, result, shift, ref status);
                result.exp -= shift;
            }
        }

        /* Check if the result is guaranteed to be one. */
        private static bool _mpd_qexp_check_one(mpd_t result, mpd_t a, ref mpd_context_t ctx, ref uint status)
        {
            mpd_t lim = MPD_NEW_CONST(0, -(ctx.prec + 1), 1, 1, 1, 9);
            mpd_t aa = MPD_NEW_SHARED(a);

            mpd_set_positive(aa);

            /* abs(a) <= 9 * 10**(-prec-1) */
            if (_mpd_cmp(aa, lim) <= 0)
            {
                _settriple(result, 0, 1, 0);
                status |= MPD_Rounded | MPD_Inexact;
                return true;
            }

            return false;
        }

        /*
         * Get the number of iterations for the Horner scheme in _mpd_qexp().
         */
        private static long _mpd_get_exp_iterations(mpd_t r, long p)
        {
            long log10pbyr; /* lower bound for log10(p / abs(r)) */
            long n;

            Debug.Assert(p >= 10);
            Debug.Assert(!mpd_iszero(r));
            Debug.Assert(-p < mpd_adjexp(r) && mpd_adjexp(r) <= -1);

            if (p > (long)(1UL << 52))
                return MPD_SSIZE_MAX;

            /*
             * Lower bound for log10(p / abs(r)): adjexp(p) - (adjexp(r) + 1)
             * At this point (for CONFIG_64, CONFIG_32 is not problematic):
             *    1) 10 <= p <= 2**52
             *    2) -p < adjexp(r) <= -1
             *    3) 1 <= log10pbyr <= 2**52 + 14
             */
            log10pbyr = (mpd_word_digits((ulong)p) - 1) - (mpd_adjexp(r) + 1);

            /*
             * The numerator in the paper is 1.435 * p - 1.182, calculated
             * exactly. We compensate for rounding errors by using 1.43503.
             * ACL2 proofs:
             *    1) exp-iter-approx-lower-bound: The term below evaluated
             *       in 53-bit floating point arithmetic is greater than or
             *       equal to the exact term used in the paper.
             *    2) exp-iter-approx-upper-bound: The term below is less than
             *       or equal to 3/2 * p <= 3/2 * 2**52.
             */
            n = (long)Math.Ceiling((1.43503 * (double)p - 1.182) / (double)log10pbyr);
            return n >= 3 ? n : 3;
        }

        // #define MPD_EXP_MAX_T 19 (CONFIG_64)
        private const long MPD_EXP_MAX_T = 19;

        /*
         * Internal function, specials have been dealt with. Apart from Overflow
         * and Underflow, two cases must be considered for the error of the result:
         *
         *   1) abs(a) <= 9 * 10**(-prec-1)  ==>  result == 1
         *
         *      Absolute error: abs(1 - e**x) < 10**(-prec)
         *      -------------------------------------------
         *
         *   2) abs(a) > 9 * 10**(-prec-1)
         *
         *      Relative error: abs(result - e**x) < 0.5 * 10**(-prec) * e**x
         *      -------------------------------------------------------------
         *
         * The algorithm is from Hull&Abrham, Variable Precision Exponential Function,
         * ACM Transactions on Mathematical Software, Vol. 12, No. 2, June 1986.
         *
         * Main differences:
         *
         *  - The number of iterations for the Horner scheme is calculated using
         *    53-bit floating point arithmetic.
         *
         *  - In the error analysis for ER (relative error accumulated in the
         *    evaluation of the truncated series) the reduced operand r may
         *    have any number of digits.
         *    ACL2 proof: exponent-relative-error
         *
         *  - The analysis for early abortion has been adapted for the mpd_t
         *    ranges.
         */
        private static void _mpd_qexp(mpd_t result, mpd_t a, ref mpd_context_t ctx, ref uint status)
        {
            mpd_context_t workctx = default;
            mpd_t tmp = MPD_NEW_STATIC(0, 0, 0, 0);
            mpd_t sum = MPD_NEW_STATIC(0, 0, 0, 0);
            mpd_t word = MPD_NEW_CONST(0, 0, 1, 1, 1, 1);
            long j, n, t;

            Debug.Assert(!mpd_isspecial(a));

            if (mpd_iszerocoeff(a))
            {
                _settriple(result, MPD_POS, 1, 0);
                return;
            }

            /*
             * We are calculating e^x = e^(r*10^t) = (e^r)^(10^t), where abs(r) < 1 and t >= 0.
             *
             * If t > 0, we have:
             *
             *   (1) 0.1 <= r < 1, so e^0.1 <= e^r. If t > MAX_T, overflow occurs:
             *
             *     MAX-EMAX+1 < log10(e^(0.1*10*t)) <= log10(e^(r*10^t)) < adjexp(e^(r*10^t))+1
             *
             *   (2) -1 < r <= -0.1, so e^r <= e^-0.1. If t > MAX_T, underflow occurs:
             *
             *     adjexp(e^(r*10^t)) <= log10(e^(r*10^t)) <= log10(e^(-0.1*10^t)) < MIN-ETINY
             */
            t = a.digits + a.exp;
            t = (t > 0) ? t : 0;
            if (t > MPD_EXP_MAX_T)
            {
                if (mpd_ispositive(a))
                {
                    mpd_setspecial(result, MPD_POS, MPD_INF);
                    status |= MPD_Overflow | MPD_Inexact | MPD_Rounded;
                }
                else
                {
                    _settriple(result, MPD_POS, 0, mpd_etiny(ref ctx));
                    status |= (MPD_Inexact | MPD_Rounded | MPD_Subnormal |
                               MPD_Underflow | MPD_Clamped);
                }
                return;
            }

            /* abs(a) <= 9 * 10**(-prec-1) */
            if (_mpd_qexp_check_one(result, a, ref ctx, ref status))
                return;

            mpd_maxcontext(ref workctx);
            workctx.prec = ctx.prec + t + 2;
            workctx.prec = (workctx.prec < 10) ? 10 : workctx.prec;
            workctx.round = MPD_ROUND_HALF_EVEN;

            if (!mpd_qcopy(result, a, ref status))
                return;
            result.exp -= t;

            /*
             * At this point:
             *    1) 9 * 10**(-prec-1) < abs(a)
             *    2) 9 * 10**(-prec-t-1) < abs(r)
             *    3) log10(9) - prec - t - 1 < log10(abs(r)) < adjexp(abs(r)) + 1
             *    4) - prec - t - 2 < adjexp(abs(r)) <= -1
             */
            n = _mpd_get_exp_iterations(result, workctx.prec);
            if (n == MPD_SSIZE_MAX)
            {
                mpd_seterror(result, MPD_Invalid_operation, ref status); /* GCOV_UNLIKELY */
                return; /* GCOV_UNLIKELY */
            }

            _settriple(sum, MPD_POS, 1, 0);

            for (j = n - 1; j >= 1; j--)
            {
                word.data[0] = (ulong)j;
                mpd_setdigits(word);
                mpd_qdiv(tmp, result, word, ref workctx, ref workctx.status);
                mpd_qfma(sum, sum, tmp, one, ref workctx, ref workctx.status);
            }

            _mpd_qpow_uint(result, sum, mpd_pow10[t], MPD_POS, ref workctx, ref status);

            mpd_del(tmp);
            mpd_del(sum);
            status |= (workctx.status & MPD_Errors);
            status |= (MPD_Inexact | MPD_Rounded);
        }

        /* exp(a) */
        public static void mpd_qexp(mpd_t result, mpd_t a, ref mpd_context_t ctx, ref uint status)
        {
            mpd_context_t workctx;

            if (mpd_isspecial(a))
            {
                if (mpd_qcheck_nan(result, a, ref ctx, ref status))
                    return;
                if (mpd_isnegative(a))
                    _settriple(result, MPD_POS, 0, 0);
                else
                    mpd_setspecial(result, MPD_POS, MPD_INF);
                return;
            }
            if (mpd_iszerocoeff(a))
            {
                _settriple(result, MPD_POS, 1, 0);
                return;
            }

            workctx = ctx;
            workctx.round = MPD_ROUND_HALF_EVEN;

            if (ctx.allcr != 0)
            {
                mpd_t t1 = MPD_NEW_STATIC(0, 0, 0, 0);
                mpd_t t2 = MPD_NEW_STATIC(0, 0, 0, 0);
                mpd_t ulp = MPD_NEW_STATIC(0, 0, 0, 0);
                mpd_t aa = MPD_NEW_STATIC(0, 0, 0, 0);
                long prec;
                long ulpexp;
                uint workstatus;

                if (result == a)
                {
                    if (!mpd_qcopy(aa, a, ref status))
                    {
                        mpd_seterror(result, MPD_Malloc_error, ref status);
                        return;
                    }
                    a = aa;
                }

                workctx.clamp = 0;
                prec = ctx.prec + 3;
                while (true)
                {
                    workctx.prec = prec;
                    workstatus = 0;

                    _mpd_qexp(result, a, ref workctx, ref workstatus);
                    status |= workstatus;

                    ulpexp = result.exp + result.digits - workctx.prec;
                    if ((workstatus & MPD_Underflow) != 0)
                    {
                        /* The effective work precision is result->digits. */
                        ulpexp = result.exp;
                    }
                    _ssettriple(ulp, MPD_POS, 1, ulpexp);

                    /*
                     * At this point [1]:
                     *   1) abs(result - e**x) < 0.5 * 10**(-prec) * e**x
                     *   2) result - ulp < e**x < result + ulp
                     *   3) result - ulp < result < result + ulp
                     *
                     * If round(result-ulp)==round(result+ulp), then
                     * round(result)==round(e**x). Therefore the result
                     * is correctly rounded.
                     *
                     * [1] If abs(a) <= 9 * 10**(-prec-1), use the absolute
                     *     error for a similar argument.
                     */
                    workctx.prec = ctx.prec;
                    mpd_qadd(t1, result, ulp, ref workctx, ref workctx.status);
                    mpd_qsub(t2, result, ulp, ref workctx, ref workctx.status);
                    if (mpd_isspecial(result) || mpd_iszerocoeff(result) ||
                        mpd_qcmp(t1, t2, ref status) == 0)
                    {
                        workctx.clamp = ctx.clamp;
                        _mpd_zeropad(result, ref workctx, ref status);
                        mpd_check_underflow(result, ref workctx, ref status);
                        mpd_qfinalize(result, ref workctx, ref status);
                        break;
                    }
                    prec += MPD_RDIGITS;
                }
                mpd_del(t1);
                mpd_del(t2);
                mpd_del(ulp);
                mpd_del(aa);
            }
            else
            {
                _mpd_qexp(result, a, ref workctx, ref status);
                _mpd_zeropad(result, ref workctx, ref status);
                mpd_check_underflow(result, ref workctx, ref status);
                mpd_qfinalize(result, ref workctx, ref status);
            }
        }

        /* Fused multiply-add: (a * b) + c, with a single final rounding. */
        public static void mpd_qfma(mpd_t result, mpd_t a, mpd_t b, mpd_t c, ref mpd_context_t ctx, ref uint status)
        {
            uint workstatus = 0;
            mpd_t cc = null;

            if (result == c)
            {
                if ((cc = mpd_qncopy(c)) == null)
                {
                    mpd_seterror(result, MPD_Malloc_error, ref status);
                    return;
                }
                c = cc;
            }

            _mpd_qmul(result, a, b, ref ctx, ref workstatus);
            if ((workstatus & MPD_Invalid_operation) == 0)
                mpd_qadd(result, result, c, ref ctx, ref workstatus);

            if (cc != null) mpd_del(cc);
            status |= workstatus;
        }

        /*
         * Schedule the optimal precision increase for the Newton iteration.
         *   v := input operand
         *   z_0 := initial approximation
         *   initprec := natural number such that abs(log(v) - z_0) < 10**-initprec
         *   maxprec := target precision
         *
         * For convenience the output klist contains the elements in reverse order:
         *   klist := [k_n-1, ..., k_0], where
         *     1) k_0 <= initprec and
         *     2) abs(log(v) - result) < 10**(-2*k_n-1 + 1) <= 10**-maxprec.
         */
        private static int ln_schedule_prec(long[] klist, long maxprec, long initprec)
        {
            long k;
            int i;

            Debug.Assert(maxprec >= 2 && initprec >= 2);
            if (maxprec <= initprec) return -1;

            i = 0; k = maxprec;
            do
            {
                k = (k + 2) / 2;
                klist[i++] = k;
            } while (k > initprec);

            return i - 1;
        }

