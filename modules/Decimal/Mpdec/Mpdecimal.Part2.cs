            Debug.Assert(prec >= 1);

            shift = MPD_MINALLOC_MAX * MPD_RDIGITS - prec;
            shift = shift < 0 ? 0 : shift;

            rnd = mpd_qshiftr(result, _mpd_ln10, shift, ref status);
            if (rnd == MPD_UINT_MAX)
