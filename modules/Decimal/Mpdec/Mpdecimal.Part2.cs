            mpd_qsub(result, a, b, ref ctx, ref workstatus);
            status |= workstatus;
            if ((workstatus & (MPD_Inexact | MPD_Rounded | MPD_Clamped)) != 0)
                mpd_seterror(result, MPD_Invalid_operation, ref status);
        }

