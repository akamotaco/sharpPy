    /// <summary>
    /// _asyncio (Modules/_asynciomodule.c of CPython v3.12.15): the accelerator of asyncio's Future and
    /// Task. One C# method per C function, named after it. What the CLR changes:
    /// the running loop lives in a [ThreadStatic] field instead of the thread state dict (the C code's
    /// cached_running_loop is then the field itself); the FutureIter free list is not kept (the CLR
    /// allocator plays that part); tp_finalize runs when the CLR collector finds the object
    /// unreachable (PyFinalizer), not when its reference count drops to zero.
    /// </summary>
    internal static class AsyncioModule
    {
        internal const int STATE_PENDING = 0;
        internal const int STATE_CANCELLED = 1;
        internal const int STATE_FINISHED = 2;

        // PySendResult
        private const int PYGEN_RETURN = 0;
        private const int PYGEN_ERROR = -1;
        private const int PYGEN_NEXT = 1;

        // ts_dict[__asyncio_running_event_loop__]: one per thread. null is "not in the dict".
        [ThreadStatic] private static PyObject _runningLoop;

        // The state of each module's types, for an object of a subclass (get_asyncio_state_by_def).
        private static readonly ConditionalWeakTable<PyType, AsyncioState> StateOfType = new();

        // ------------------------------------------------------------------ helpers

        private static PythonException SetString(PyObject excType, string message) =>
            new((PyBaseException)excType.Call(new PyObject[] { PyString.From(message) }, null));

        private static string R(PyObject o) => o.ToRepr().Value;

        private static AsyncioState StateFor(PyType cls)
        {
            foreach (var t in cls.MRO)
                if (StateOfType.TryGetValue(t, out var st))
                    return st;
            throw PyTypeError.Create($"{cls.Name} is not an _asyncio type");
        }

        private static bool Future_CheckExact(AsyncioState state, PyObject obj) =>
            ReferenceEquals(obj.GetPyType(), state.FutureType);

        private static bool Task_CheckExact(AsyncioState state, PyObject obj) =>
            ReferenceEquals(obj.GetPyType(), state.TaskType);

        // PyObject_IsTrue of an object, raising what __bool__ raises.
        private static bool IsTrue(PyObject o) => o.IsTrue();

        // PyObject_RichCompareBool(a, b, Py_EQ)
        private static bool RichCompareEq(PyObject left, PyObject right)
        {
            if (ReferenceEquals(left, right)) return true;
            var result = PyObject.Compare(left, right, PyObject.CompareOp.EQ);
            return result != null && result.IsTrue();
        }

        // PyErr_GivenExceptionMatches(exc, type) for an exception instance and a class
        private static bool ExceptionMatches(PyObject exc, PyObject type) =>
            type is PyType t && exc.GetPyType().IsSubclassOf(t);

        // PyIter_Send: a generator or coroutine resumed directly, None to an iterator its tp_iternext,
        // else its send method; StopIteration is the return value.
        private static int PyIter_Send(PyObject iter, PyObject arg, out PyObject result)
        {
            try
            {
                if (PyGenerator.NativeCore(iter) is { } native)
                    result = native.Send(arg);
                else if (arg is PyNone && iter.IsIterator)
                    result = iter.Next();
                else
                    result = iter.GetAttribute("send").Call(new[] { arg }, null);
                return PYGEN_NEXT;
            }
            catch (PythonException error) when (error.PyException is PyStopIteration stop)
            {
                // _PyGen_FetchStopIterationValue
                result = stop.Value ?? PyNone.Instance;
                return PYGEN_RETURN;
            }
        }

        // ------------------------------------------------------------------ coroutine checks

        // _is_coroutine
        private static bool _is_coroutine(AsyncioState state, PyObject coro)
        {
            /* 'coro' is not a native coroutine, call asyncio.iscoroutine() to check if it's another
               coroutine flavour. */
            var res = state.asyncio_iscoroutine_func.Call(new[] { coro }, null);
            if (!IsTrue(res))
                return false;
            if (state.iscoroutine_typecache.Items.Count < 100)
            {
                /* Just in case we don't want to cache more than 100 positive types. */
                state.iscoroutine_typecache.Add(coro.GetPyType());
            }
            return true;
        }

        // is_coroutine
        private static bool is_coroutine(AsyncioState state, PyObject coro)
        {
            if (coro is SharpPy.Core.PyCoroutine && coro.GetPyType() == PyType.CoroutineType)
                return true;
            /* Check if `type(coro)` is in the cache. */
            if (state.iscoroutine_typecache.ContainsItem(coro.GetPyType()).IsTrue())
                return true;
            return _is_coroutine(state, coro);
        }

        // get_future_loop: asyncio.futures._get_loop
        private static PyObject get_future_loop(AsyncioState state, PyObject fut)
        {
            if (Future_CheckExact(state, fut) || Task_CheckExact(state, fut))
                return ((FutureObj)fut).fut_loop;
            var getloop = fut.LookupAttribute("get_loop");
            if (getloop != null)
                return getloop.Call(Array.Empty<PyObject>(), null);
            return fut.GetAttribute("_loop");
        }

        // get_running_loop: the loop, or null when there is none (or it is None).
        private static PyObject get_running_loop(AsyncioState state)
        {
            var rl = _runningLoop;
            if (rl == null || rl is PyNone)
                return null;
            return rl;
        }

        // set_running_loop
        private static void set_running_loop(AsyncioState state, PyObject loop) => _runningLoop = loop;

        // get_event_loop
        private static PyObject get_event_loop(AsyncioState state)
        {
            var loop = get_running_loop(state);
            if (loop != null)
                return loop;
            var policy = state.asyncio_get_event_loop_policy.Call(Array.Empty<PyObject>(), null);
            return policy.GetAttribute("get_event_loop").Call(Array.Empty<PyObject>(), null);
        }

        // call_soon: loop.call_soon(func, arg) or loop.call_soon(func[, arg], context=ctx)
        private static void call_soon(AsyncioState state, PyObject loop, PyObject func, PyObject arg, PyObject ctx)
        {
            var method = loop.GetAttribute("call_soon");
            if (ctx == null)
            {
                method.Call(new[] { func, arg }, null);
                return;
            }
            var kwargs = new PyDict();
            kwargs.SetItemStorage(PyString.From("context"), ctx);
            method.Call(arg != null ? new[] { func, arg } : new[] { func }, kwargs);
        }

        // future_is_alive
        internal static bool future_is_alive(FutureObj fut) => fut.fut_loop != null;

        // future_ensure_alive
        private static void future_ensure_alive(FutureObj fut)
        {
            if (!future_is_alive(fut))
                throw PyRuntimeError.Create("Future object is not initialized.");
        }

        // future_schedule_callbacks
        private static void future_schedule_callbacks(AsyncioState state, FutureObj fut)
        {
            if (fut.fut_callback0 != null)
            {
                /* There's a 1st callback */
                // Beware: An evil call_soon could alter fut_callback0 or fut_context0; ownership is
                // transferred before the call.
                var fut_callback0 = fut.fut_callback0;
                fut.fut_callback0 = null;
                var fut_context0 = fut.fut_context0;
                fut.fut_context0 = null;
                try
                {
                    call_soon(state, fut.fut_loop, fut_callback0, fut, fut_context0);
                }
                catch (PythonException)
                {
                    /* If an error occurs in pure-Python implementation, all callbacks are cleared. */
                    fut.fut_callbacks = null;
                    throw;
                }
                /* we called the first callback, now try calling callbacks from the 'fut_callbacks'
                   list. */
            }

            if (fut.fut_callbacks == null)
                return;

            // Beware: An evil call_soon could change fut->fut_callbacks.
            var callbacks = fut.fut_callbacks;
            fut.fut_callbacks = null;
            int n = callbacks.RawCount();
            for (int i = 0; i < n; i++)
            {
                var cb_tup = (PyTuple)callbacks.RawGet(i);
                call_soon(state, fut.fut_loop, cb_tup.Items[0], fut, cb_tup.Items[1]);
            }
        }

        // future_init
        internal static void future_init(FutureObj fut, PyObject loop)
        {
            // Same to FutureObj_clear() but not clearing fut->dict
            fut.fut_loop = null;
            fut.fut_callback0 = null;
            fut.fut_context0 = null;
            fut.fut_callbacks = null;
            fut.fut_result = null;
            fut.fut_exception = null;
            fut.fut_exception_tb = null;
            fut.fut_source_tb = null;
            fut.fut_cancel_msg = null;
            fut.fut_cancelled_exc = null;

            fut.fut_state = STATE_PENDING;
            fut.fut_log_tb = false;
            fut.fut_blocking = false;

            if (loop is PyNone)
                loop = get_event_loop(fut.St);
            fut.fut_loop = loop;

            var res = fut.fut_loop.GetAttribute("get_debug").Call(Array.Empty<PyObject>(), null);
            if (IsTrue(res) && !PyGil.Finalizing)
            {
                /* Only try to capture the traceback if the interpreter is not being finalized. */
                fut.fut_source_tb = fut.St.traceback_extract_stack.Call(Array.Empty<PyObject>(), null);
            }
        }

        // future_set_result
        private static PyObject future_set_result(AsyncioState state, FutureObj fut, PyObject res)
        {
            future_ensure_alive(fut);
            if (fut.fut_state != STATE_PENDING)
                throw SetString(state.asyncio_InvalidStateError, "invalid state");
            fut.fut_result = res;
            fut.fut_state = STATE_FINISHED;
            future_schedule_callbacks(state, fut);
            return PyNone.Instance;
        }

        // future_set_exception
        private static PyObject future_set_exception(AsyncioState state, FutureObj fut, PyObject exc)
        {
            PyObject exc_val;
            if (fut.fut_state != STATE_PENDING)
                throw SetString(state.asyncio_InvalidStateError, "invalid state");

            // PyExceptionClass_Check
            if (exc is PyType cls && cls.IsSubclassOf(PyType.BaseExceptionType))
            {
                exc_val = exc.Call(Array.Empty<PyObject>(), null);
                if (fut.fut_state != STATE_PENDING)
                    throw SetString(state.asyncio_InvalidStateError, "invalid state");
            }
            else
            {
                exc_val = exc;
            }
            if (exc_val is not PyBaseException)
                throw PyTypeError.Create("invalid exception object");
            if (ExceptionMatches(exc_val, PyType.StopIterationType))
            {
                const string msg = "StopIteration interacts badly with generators and cannot be raised into a Future";
                var err = (PyBaseException)PyType.RuntimeErrorType.Call(new PyObject[] { PyString.From(msg) }, null);
                err.__cause__ = (PyBaseException)exc_val;
                err.__suppress_context__ = true;
                err.__context__ = (PyBaseException)exc_val;
                exc_val = err;
            }

            fut.fut_exception = exc_val;
            fut.fut_exception_tb = ((PyBaseException)exc_val).__traceback__;
            fut.fut_state = STATE_FINISHED;

            future_schedule_callbacks(state, fut);

            fut.fut_log_tb = true;
            // tp_finalize must run for this object now that it has a traceback to log.
            PyFinalizer.Attach(fut);
            return PyNone.Instance;
        }

        // create_cancelled_error
        private static PyObject create_cancelled_error(AsyncioState state, FutureObj fut)
        {
            if (fut.fut_cancelled_exc != null)
            {
                /* transfer ownership */
                var exc = fut.fut_cancelled_exc;
                fut.fut_cancelled_exc = null;
                return exc;
            }
            var msg = fut.fut_cancel_msg;
            if (msg == null || msg is PyNone)
                return state.asyncio_CancelledError.Call(Array.Empty<PyObject>(), null);
            return state.asyncio_CancelledError.Call(new[] { msg }, null);
        }

        // future_set_cancelled_error: PyErr_SetObject(CancelledError, exc)
        private static PythonException future_set_cancelled_error(AsyncioState state, FutureObj fut)
        {
            var exc = create_cancelled_error(state, fut);
            return new PythonException((PyBaseException)exc);
        }

        // future_get_result: 0 and the result, 1 and the exception, or raises.
        private static int future_get_result(AsyncioState state, FutureObj fut, out PyObject result)
        {
            if (fut.fut_state == STATE_CANCELLED)
                throw future_set_cancelled_error(state, fut);
            if (fut.fut_state != STATE_FINISHED)
                throw SetString(state.asyncio_InvalidStateError, "Result is not set.");

            fut.fut_log_tb = false;
            if (fut.fut_exception != null)
            {
                // PyException_SetTraceback(fut_exception, tb or None)
                ((PyBaseException)fut.fut_exception).__traceback__ = fut.fut_exception_tb as PyTraceback;
                result = fut.fut_exception;
                fut.fut_exception_tb = null;
                return 1;
            }
            result = fut.fut_result;
            return 0;
        }

        // future_add_done_callback
        private static PyObject future_add_done_callback(AsyncioState state, FutureObj fut, PyObject arg, PyObject ctx)
        {
            if (!future_is_alive(fut))
                throw PyRuntimeError.Create("uninitialized Future object");

            if (fut.fut_state != STATE_PENDING)
            {
                /* The future is done/cancelled, so schedule the callback right away. */
                call_soon(state, fut.fut_loop, arg, fut, ctx);
            }
            else
            {
                /* The future is pending, add a callback.
                   callback0 -- a pointer to the first callback
                   callbacks -- a list of 2nd, 3rd, ... callbacks */
                if (fut.fut_callbacks == null && fut.fut_callback0 == null)
                {
                    fut.fut_callback0 = arg;
                    fut.fut_context0 = ctx;
                }
                else
                {
                    var tup = PyTuple.From(new[] { arg, ctx });
                    if (fut.fut_callbacks != null)
                        fut.fut_callbacks.Append(tup);
                    else
                        fut.fut_callbacks = new PyList(tup);
                }
            }
            return PyNone.Instance;
        }

        // future_cancel
        private static PyObject future_cancel(AsyncioState state, FutureObj fut, PyObject msg)
        {
            fut.fut_log_tb = false;
            if (fut.fut_state != STATE_PENDING)
                return PyBool.False;
            fut.fut_state = STATE_CANCELLED;
            fut.fut_cancel_msg = msg;
            future_schedule_callbacks(state, fut);
            return PyBool.True;
        }

        // _asyncio_Future___init___impl
        private static void _asyncio_Future___init___impl(FutureObj self, PyObject loop) => future_init(self, loop);

        // FutureObj_clear
        private static void FutureObj_clear(FutureObj fut)
        {
            fut.fut_loop = null;
            fut.fut_callback0 = null;
            fut.fut_context0 = null;
            fut.fut_callbacks = null;
            fut.fut_result = null;
            fut.fut_exception = null;
            fut.fut_exception_tb = null;
            fut.fut_source_tb = null;
            fut.fut_cancel_msg = null;
            fut.fut_cancelled_exc = null;
            fut.SetObjectDict(null);
        }

        // _asyncio_Future_result_impl
        private static PyObject _asyncio_Future_result_impl(FutureObj self)
        {
            var state = self.St;
            if (!future_is_alive(self))
                throw SetString(state.asyncio_InvalidStateError, "Future object is not initialized.");
            int res = future_get_result(state, self, out var result);
            if (res == 0)
                return result;
            // PyErr_SetObject(PyExceptionInstance_Class(result), result)
            throw new PythonException((PyBaseException)result);
        }

        // _asyncio_Future_exception_impl
        private static PyObject _asyncio_Future_exception_impl(FutureObj self)
        {
            var state = self.St;
            if (!future_is_alive(self))
                throw SetString(state.asyncio_InvalidStateError, "Future object is not initialized.");
            if (self.fut_state == STATE_CANCELLED)
                throw future_set_cancelled_error(state, self);
            if (self.fut_state != STATE_FINISHED)
                throw SetString(state.asyncio_InvalidStateError, "Exception is not set.");
            if (self.fut_exception != null)
            {
                self.fut_log_tb = false;
                return self.fut_exception;
            }
            return PyNone.Instance;
        }

        // _asyncio_Future_set_result_impl
        private static PyObject _asyncio_Future_set_result_impl(FutureObj self, PyObject result)
