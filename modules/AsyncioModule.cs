        // _asyncio_Task___init___impl
        private static void _asyncio_Task___init___impl(TaskObj self, PyObject coro, PyObject loop, PyObject name,
            PyObject context, bool eager_start)
        {
            future_init(self, loop);

            var state = self.St;
            if (!is_coroutine(state, coro))
            {
                self.task_log_destroy_pending = false;
                throw PyTypeError.Create($"a coroutine was expected, got {R(coro)}");
            }

            if (context is PyNone)
                self.task_context = _ContextvarsModule.PyContext_CopyCurrent();
            else
                self.task_context = context;

            self.task_fut_waiter = null;
            self.task_must_cancel = false;
            self.task_log_destroy_pending = true;
            self.task_num_cancels_requested = 0;
            self.task_coro = coro;
            // TaskObj_finalize reports a task destroyed while pending.
            PyFinalizer.Attach(self);

            if (name is PyNone)
            {
                // optimization: defer task name formatting; store the task counter as PyLong in the
                // name for deferred formatting in get_name
                name = PyInt.From(++state.task_name_counter);
            }
            else if (!(name is PyString && name.GetPyType() == PyType.StrType))
            {
                name = name.ToStr();
            }
            self.task_name = name;

            if (eager_start)
            {
                var res = loop.GetAttribute("is_running").Call(Array.Empty<PyObject>(), null);
                bool is_loop_running = ReferenceEquals(res, PyBool.True);
                if (is_loop_running)
                {
                    task_eager_start(state, self);
                    return;
                }
            }

            task_call_step_soon(state, self, null);
            register_task(state, self);
        }

