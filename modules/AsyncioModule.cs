        // _asyncio_Future_add_done_callback_impl
        private static PyObject _asyncio_Future_add_done_callback_impl(FutureObj self, PyObject fn, PyObject context)
        {
            if (context == null)
                context = _ContextvarsModule.PyContext_CopyCurrent();
            return future_add_done_callback(self.St, self, fn, context);
        }

        // _asyncio_Future_remove_done_callback_impl
        private static PyObject _asyncio_Future_remove_done_callback_impl(FutureObj self, PyObject fn)
        {
            long cleared_callback0 = 0;
            future_ensure_alive(self);

            if (self.fut_callback0 != null)
            {
                // Beware: An evil PyObject_RichCompareBool could free fut_callback0.
                var fut_callback0 = self.fut_callback0;
                if (RichCompareEq(fut_callback0, fn))
                {
                    /* callback0 == fn */
                    self.fut_callback0 = null;
                    self.fut_context0 = null;
                    cleared_callback0 = 1;
                }
            }

            if (self.fut_callbacks == null)
                return PyInt.From(cleared_callback0);

            long len = self.fut_callbacks.RawCount();
            if (len == 0)
            {
                self.fut_callbacks = null;
                return PyInt.From(cleared_callback0);
            }

            if (len == 1)
            {
                var cb_tup = (PyTuple)self.fut_callbacks.RawGet(0);
                if (RichCompareEq(cb_tup.Items[0], fn))
                {
                    /* callbacks[0] == fn */
                    self.fut_callbacks = null;
                    return PyInt.From(1 + cleared_callback0);
                }
                /* callbacks[0] != fn and len(callbacks) == 1 */
                return PyInt.From(cleared_callback0);
            }

            var newlist = new List<PyObject>((int)len);
            // Beware: PyObject_RichCompareBool below may change fut_callbacks. See GH-97592.
            for (int i = 0; self.fut_callbacks != null && i < self.fut_callbacks.RawCount(); i++)
            {
                var item = (PyTuple)self.fut_callbacks.RawGet(i);
                if (!RichCompareEq(item.Items[0], fn))
                    newlist.Add(item);
            }

            // Note: fut_callbacks may have been cleared.
            int j = newlist.Count;
            if (j == 0 || self.fut_callbacks == null)
            {
                self.fut_callbacks = null;
                return PyInt.From(len + cleared_callback0);
            }

            len = self.fut_callbacks.RawCount();
            if (j != len)
            {
                // PyList_SetSlice(fut_callbacks, 0, len, newlist)
                self.fut_callbacks.Clear();
                foreach (var item in newlist)
                    self.fut_callbacks.Append(item);
            }
            return PyInt.From(len - j + cleared_callback0);
        }

