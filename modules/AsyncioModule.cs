        private static PyObject FutureIter_send(FutureIterObj self, PyObject unused)
        {
            /* Future.__iter__ doesn't care about values that are pushed to the generator, it just
               returns self.result(). */
            return FutureIter_iternext(self);
        }

        // FutureIter_throw
        private static PyObject FutureIter_throw(FutureIterObj self, PyObject[] args)
        {
            PyObject type, val = null, tb = null;
            PyArgs.Positional("throw", args, null, 1, 3);
            if (args.Length > 1)
                PyWarnings.DeprecatedThrow();

            type = args[0];
            if (args.Length == 3)
            {
                val = args[1];
                tb = args[2];
            }
            else if (args.Length == 2)
            {
                val = args[1];
            }

            if (val is PyNone)
                val = null;
            if (tb is PyNone)
                tb = null;
            else if (tb != null && tb is not PyTraceback)
                throw PyTypeError.Create("throw() third argument must be a traceback");

            PyBaseException exc;
            if (type is PyType cls && cls.IsSubclassOf(PyType.BaseExceptionType))
            {
                // PyErr_NormalizeException
                exc = PySuspensionException.Normalize(type, val, tb).PyException;
            }
            else if (type is PyBaseException instance)
            {
                if (val != null)
                    throw PyTypeError.Create("instance exception may not have a separate value");
                exc = instance;
                if (tb != null)
                    exc.__traceback__ = (PyTraceback)tb;
            }
            else
            {
                throw PyTypeError.Create("exceptions must be classes deriving BaseException or instances of such a class");
            }

            self.future = null;
            // PyErr_Restore(type, val, tb): the traceback travels with the exception.
            return ThrowRestored(exc);
        }

        private static PyObject ThrowRestored(PyBaseException exc) => throw new PythonException(exc);

