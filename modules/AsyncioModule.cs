        /// <summary>PyInit__asyncio and module_exec.</summary>
        internal static PyModule Create()
        {
            var module = new PyModule("_asyncio");
            var state = new AsyncioState();

            state.TaskStepMethWrapper_Type = MakeTaskStepMethWrapperType(state);
            state.FutureIterType = MakeFutureIterType(state);
            state.FutureType = MakeFutureType(state);
            state.TaskType = MakeTaskType(state, state.FutureType);
            state.TaskWakeupDef = MakeTaskWakeupDef(state.TaskType);
            foreach (var type in new[] { state.TaskStepMethWrapper_Type, state.FutureIterType, state.FutureType, state.TaskType })
                StateOfType.Add(type, state);

            // asyncio_methods
            var d = module.ModuleDict;
            d["current_task"] = Function("current_task", (args, kwargs) =>
            {
                var a = PyArgs.Unpack("current_task", args, kwargs, new[] { "loop" }, 0, 0, 1);
                return _asyncio_current_task_impl(state, a[0] ?? PyNone.Instance);
            });
            d["get_event_loop"] = PyArgs.NoArgsFunction("_asyncio", "get_event_loop", () => _asyncio_get_event_loop_impl(state));
            d["get_running_loop"] = PyArgs.NoArgsFunction("_asyncio", "get_running_loop", () => _asyncio_get_running_loop_impl(state));
            d["_get_running_loop"] = PyArgs.NoArgsFunction("_asyncio", "_get_running_loop", () => _asyncio__get_running_loop_impl(state));
            d["_set_running_loop"] = PyArgs.MethO("_asyncio", "_set_running_loop", args => _asyncio__set_running_loop(state, args[0]));
            foreach (var (name, body) in new (string, Func<AsyncioState, PyObject, PyObject>)[]
            {
                ("_register_task", _asyncio__register_task_impl),
                ("_register_eager_task", _asyncio__register_eager_task_impl),
                ("_unregister_task", _asyncio__unregister_task_impl),
                ("_unregister_eager_task", _asyncio__unregister_eager_task_impl),
            })
            {
                var fname = name;
                var impl = body;
                d[fname] = Function(fname, (args, kwargs) =>
                    impl(state, PyArgs.Unpack(fname, args, kwargs, new[] { "task" }, 0, 1, 1)[0]));
            }
            foreach (var (name, body) in new (string, Func<AsyncioState, PyObject, PyObject, PyObject>)[]
            {
                ("_enter_task", _asyncio__enter_task_impl),
                ("_leave_task", _asyncio__leave_task_impl),
                ("_swap_current_task", _asyncio__swap_current_task_impl),
            })
            {
                var fname = name;
                var impl = body;
                d[fname] = Function(fname, (args, kwargs) =>
                {
                    var a = PyArgs.Unpack(fname, args, kwargs, new[] { "loop", "task" }, 0, 2, 2);
                    return impl(state, a[0], a[1]);
                });
            }

            d["Future"] = state.FutureType;
            d["Task"] = state.TaskType;
            // Must be done after types are added to avoid a circular dependency
            module_init(state);
            d["_scheduled_tasks"] = state.scheduled_tasks;
            d["_eager_tasks"] = state.eager_tasks;
            d["_current_tasks"] = state.current_tasks;
            return module;
        }

