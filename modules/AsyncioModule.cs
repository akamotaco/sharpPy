        // FutureIter_am_send
        private static int FutureIter_am_send(FutureIterObj it, out PyObject result)
        {
            /* arg is unused, see the comment on FutureIter_send for clarification */
            result = null;
            var fut = it.future;
            if (fut == null)
                return PYGEN_ERROR;

            if (fut.fut_state == STATE_PENDING)
            {
                if (!fut.fut_blocking)
                {
                    fut.fut_blocking = true;
                    result = fut;
                    return PYGEN_NEXT;
                }
                throw PyRuntimeError.Create("await wasn't used with future");
            }

            it.future = null;
            result = _asyncio_Future_result_impl(fut);
            return PYGEN_RETURN;
        }

        // FutureIter_iternext
        internal static PyObject FutureIter_iternext(FutureIterObj it)
        {
            switch (FutureIter_am_send(it, out var result))
            {
                case PYGEN_RETURN:
                    // _PyGen_SetStopIterationValue
                    throw StopIterationWithValue(result);
                case PYGEN_NEXT:
                    return result;
                default:
                    // PYGEN_ERROR without an exception set: iteration simply ends.
                    throw PyStopIteration.Create();
            }
        }

        // _PyGen_SetStopIterationValue: a tuple or an exception is wrapped as StopIteration's argument.
        private static Exception StopIterationWithValue(PyObject value)
        {
            if (value is PyNone)
                return PyStopIteration.Create();
            var exc = (PyBaseException)PyType.StopIterationType.Call(new[] { value }, null);
            return new PythonException(exc);
        }

