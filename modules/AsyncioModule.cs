        // FutureObj_get_callbacks
        private static PyObject FutureObj_get_callbacks(FutureObj fut)
        {
            future_ensure_alive(fut);
            int len = 0;
            if (fut.fut_callback0 != null)
                len++;
            if (fut.fut_callbacks != null)
                len += fut.fut_callbacks.RawCount();
            if (len == 0)
                return PyNone.Instance;

            var callbacks = new PyList();
            if (fut.fut_callback0 != null)
                callbacks.Append(PyTuple.From(new[] { fut.fut_callback0, fut.fut_context0 }));
            if (fut.fut_callbacks != null)
                for (int j = 0; j < fut.fut_callbacks.RawCount(); j++)
                    callbacks.Append(fut.fut_callbacks.RawGet(j));
            return callbacks;
        }

