        // FutureObj_finalize
        internal static void FutureObj_finalize(FutureObj fut)
        {
            if (!fut.fut_log_tb)
                return;
            fut.fut_log_tb = false;

            /* Save the current exception, if any. (The finalizer path saves and restores it.) */
            var context = new PyDict();
            var message = PyString.From($"{fut.GetPyType().Name} exception was never retrieved");
            context.SetItemStorage(PyString.From("message"), message);
            context.SetItemStorage(PyString.From("exception"), fut.fut_exception);
            context.SetItemStorage(PyString.From("future"), fut);
            if (fut.fut_source_tb != null)
                context.SetItemStorage(PyString.From("source_traceback"), fut.fut_source_tb);

            CallExceptionHandler(fut.fut_loop, context);
        }

        // func = loop.call_exception_handler; func(context), an error reported as unraisable.
        private static void CallExceptionHandler(PyObject loop, PyDict context)
        {
            PyObject func;
            try
            {
                func = loop.GetAttribute("call_exception_handler");
            }
            catch (PythonException)
            {
                // PyObject_GetAttr failed: the error is restored over by the saved one.
                return;
            }
            try
            {
                func.Call(new PyObject[] { context }, null);
            }
            catch (PythonException error)
            {
                PyUnraisable.Report(error, func);
            }
        }

