        // task_step_impl
        private static PyObject task_step_impl(AsyncioState state, TaskObj task, PyObject exc)
        {
            bool clear_exc = false;
            PyObject result;

            if (task.fut_state != STATE_PENDING)
                throw SetString(state.asyncio_InvalidStateError,
                    $"_step(): already done: {R(task)} {R(exc ?? PyNone.Instance)}");

            if (task.task_must_cancel)
            {
                if (exc != null)
                {
                    /* Check if exc is a CancelledError */
                    if (!BuiltinsModule.IsInstance(new[] { exc, state.asyncio_CancelledError }).IsTrue())
                    {
                        /* exc is not CancelledError; reset it to NULL */
                        exc = null;
                    }
                }
                if (exc == null)
                {
                    /* exc was not a CancelledError */
                    exc = create_cancelled_error(state, task);
                    clear_exc = true;
                }
                task.task_must_cancel = false;
            }
            _ = clear_exc;

            task.task_fut_waiter = null;

            var coro = task.task_coro;
            if (coro == null)
                throw PyRuntimeError.Create("uninitialized Task object");

            int gen_status;
            PythonException raised = null;
            try
            {
                if (exc == null)
                {
                    gen_status = PyIter_Send(coro, PyNone.Instance, out result);
                }
                else
                {
                    try
                    {
                        result = coro.GetAttribute("throw").Call(new[] { exc }, null);
                        gen_status = PYGEN_NEXT;
                    }
                    catch (PythonException error) when (error.PyException is PyStopIteration stop)
                    {
                        // gen_status_from_result
                        result = stop.Value ?? PyNone.Instance;
                        gen_status = PYGEN_RETURN;
                    }
                }
            }
            catch (PythonException error)
            {
                raised = error;
                result = null;
                gen_status = PYGEN_ERROR;
            }

            if (gen_status == PYGEN_RETURN || gen_status == PYGEN_ERROR)
            {
                if (result != null)
                {
                    /* The error is StopIteration and that means that the underlying coroutine has
                       resolved */
                    if (task.task_must_cancel)
                    {
                        // Task is cancelled right before coro stops.
                        task.task_must_cancel = false;
                        future_cancel(state, task, task.fut_cancel_msg);
                    }
                    else
                    {
                        future_set_result(state, task, result);
                    }
                    return PyNone.Instance;
                }

                var raisedExc = raised.PyException;
                if (ExceptionMatches(raisedExc, state.asyncio_CancelledError))
                {
                    /* CancelledError */
                    /* transfer ownership */
                    task.fut_cancelled_exc = raisedExc;
                    return future_cancel(state, task, null);
                }

                /* Some other exception; pop it and call Task.set_exception() */
                future_set_exception(state, task, raisedExc);

                if (ExceptionMatches(raisedExc, PyType.KeyboardInterruptType) ||
                    ExceptionMatches(raisedExc, PyType.SystemExitType))
                {
                    /* We've got a KeyboardInterrupt or a SystemError; re-raise it */
                    throw new PythonException(raisedExc, fromReraise: true);
                }
                return PyNone.Instance;
            }

            return task_step_handle_result_impl(state, task, result);
        }

        // task_step_handle_result_impl
        private static PyObject task_step_handle_result_impl(AsyncioState state, TaskObj task, PyObject result)
        {
            if (ReferenceEquals(result, task))
            {
                /* We have a task that wants to await on itself */
                return task_set_error_soon(state, task, PyType.RuntimeErrorType,
                    $"Task cannot await on itself: {R(task)}");
            }

            /* Check if `result` is FutureObj or TaskObj (and not a subclass) */
            if (Future_CheckExact(state, result) || Task_CheckExact(state, result))
            {
                var fut = (FutureObj)result;

                /* Check if `result` future is attached to a different loop */
                if (!ReferenceEquals(fut.fut_loop, task.fut_loop))
                    return different_loop(state, task, result);

                if (!fut.fut_blocking)
                    return yield_insteadof_yf(state, task, result);

                fut.fut_blocking = false;

                /* result.add_done_callback(task._wakeup) */
                var wrapper = TaskWakeup(task);
                future_add_done_callback(state, fut, wrapper, task.task_context);

                /* task._fut_waiter = result */
                task.task_fut_waiter = result;

                if (task.task_must_cancel)
                {
                    // Beware: An evil `__getattribute__` could prematurely delete task_cancel_msg.
                    var task_cancel_msg = task.fut_cancel_msg;
                    var r = result.GetAttribute("cancel").Call(new[] { task_cancel_msg ?? PyNone.Instance }, null);
                    if (IsTrue(r))
                        task.task_must_cancel = false;
                }
                return PyNone.Instance;
            }

            /* Check if `result` is None */
            if (result is PyNone)
            {
                /* Bare yield relinquishes control for one event loop iteration. */
                task_call_step_soon(state, task, null);
                return result;
            }

            /* Check if `result` is a Future-compatible object */
            var o = result.LookupAttribute("_asyncio_future_blocking");
            if (o != null && o is not PyNone)
            {
                /* `result` is a Future-compatible object */
                bool blocking = IsTrue(o);

                /* Check if `result` future is attached to a different loop */
                var oloop = get_future_loop(state, result);
                if (!ReferenceEquals(oloop, task.fut_loop))
                    return different_loop(state, task, result);

                if (!blocking)
                    return yield_insteadof_yf(state, task, result);

                /* result._asyncio_future_blocking = False */
                result.SetAttribute("_asyncio_future_blocking", PyBool.False);

                var wrapper = TaskWakeup(task);

                /* result.add_done_callback(task._wakeup) */
                var add_cb = result.GetAttribute("add_done_callback");
                var kwargs = new PyDict();
                kwargs.SetItemStorage(PyString.From("context"), task.task_context);
                add_cb.Call(new[] { wrapper }, kwargs);

                /* task._fut_waiter = result */
                task.task_fut_waiter = result;

                if (task.task_must_cancel)
                {
                    var task_cancel_msg = task.fut_cancel_msg;
                    var r = result.GetAttribute("cancel").Call(new[] { task_cancel_msg ?? PyNone.Instance }, null);
                    if (IsTrue(r))
                        task.task_must_cancel = false;
                }
                return PyNone.Instance;
            }

            /* Check if `result` is a generator */
            if (BuiltinsModule.IsInstance(new PyObject[] { result, PyType.GeneratorType }).IsTrue())
            {
                /* `result` is a generator */
                return task_set_error_soon(state, task, PyType.RuntimeErrorType,
                    $"yield was used instead of yield from for generator in task {R(task)} with {R(result)}");
            }

            /* The `result` is none of the above */
            return task_set_error_soon(state, task, PyType.RuntimeErrorType, $"Task got bad yield: {R(result)}");
        }

        // task_step_handle_result_impl's yield_insteadof_yf label
        private static PyObject yield_insteadof_yf(AsyncioState state, TaskObj task, PyObject result) =>
            task_set_error_soon(state, task, PyType.RuntimeErrorType,
                $"yield was used instead of yield from in task {R(task)} with {R(result)}");

        // task_step_handle_result_impl's different_loop label
        private static PyObject different_loop(AsyncioState state, TaskObj task, PyObject result) =>
            task_set_error_soon(state, task, PyType.RuntimeErrorType,
                $"Task {R(task)} got Future {R(result)} attached to a different loop");

        // task_step
        private static PyObject task_step(AsyncioState state, TaskObj task, PyObject exc)
        {
            enter_task(state, task.fut_loop, task);
            PyObject res;
            try
            {
                res = task_step_impl(state, task, exc);
            }
            catch (PythonException error)
            {
                // leave_task, and _PyErr_ChainExceptions1(exc) if that fails too.
                try
                {
                    leave_task(state, task.fut_loop, task);
                }
                catch (PythonException leaveError)
                {
                    leaveError.PyException.__context__ ??= error.PyException;
                    throw;
                }
                throw;
            }
            leave_task(state, task.fut_loop, task);
            return res;
        }

        // task_eager_start
        private static void task_eager_start(AsyncioState state, TaskObj task)
        {
            var prevtask = swap_current_task(state, task.fut_loop, task);
            register_eager_task(state, task);
            _ContextvarsModule.PyContext_Enter(task.task_context);

            PythonException failure = null;
            try
            {
                task_step_impl(state, task, null);
            }
            catch (PythonException error)
            {
                failure = error;
            }

            try
            {
                swap_current_task(state, task.fut_loop, prevtask);
            }
            catch (PythonException error)
            {
                failure ??= error;
            }
            try
            {
                unregister_eager_task(state, task);
            }
            catch (PythonException error)
            {
                failure ??= error;
            }
            try
            {
                _ContextvarsModule.PyContext_Exit(task.task_context);
            }
            catch (PythonException error)
            {
                failure ??= error;
            }

            if (task.fut_state == STATE_PENDING)
            {
                try
                {
                    register_task(state, task);
                }
                catch (PythonException error)
                {
                    failure ??= error;
                }
            }
            else
            {
                // This seems to really help performance on pyperformance benchmarks
                task.task_coro = null;
            }

            if (failure != null)
                throw failure;
        }

        // task_wakeup
        private static PyObject task_wakeup(TaskObj task, PyObject o)
        {
            var state = task.St;
            PythonException raised;
            if (Future_CheckExact(state, o) || Task_CheckExact(state, o))
            {
                int res;
                PyObject fut_result;
                try
                {
                    res = future_get_result(state, (FutureObj)o, out fut_result);
                }
                catch (PythonException error)
                {
                    raised = error; /* exception raised */
                    goto step_with_exception;
                }
                if (res == 0)
                    return task_step(state, task, null);
                return task_step(state, task, fut_result);
            }
            else
            {
                try
                {
                    o.GetAttribute("result").Call(Array.Empty<PyObject>(), null);
                }
                catch (PythonException error)
                {
                    raised = error; /* exception raised */
                    goto step_with_exception;
                }
                return task_step(state, task, null);
            }

        step_with_exception:
            return task_step(state, task, raised.PyException);
        }

