#!/usr/bin/env python3
"""Generate Lib/_ast.py and runtime/compiler/PythonAst.g.cs from Parser/Python.asdl.

Python/Python-ast.c is generated the same way by Parser/asdl_c.py. Node classes live in Python,
the conversion between the ASDL tree of the compiler and those objects lives in C#.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CPYTHON = os.path.join(os.path.dirname(ROOT), "cpython-v3.12.15")
sys.path.insert(0, os.path.join(CPYTHON, "Parser"))
import asdl  # noqa: E402

CLASS_NAMES = {"Expr": "GeneratedExprStmt", "Mod": "GeneratedMod_", "TypeIgnore": "GeneratedTypeIgnoreNode"}
SUM_BASE = {"mod": "GeneratedMod", "stmt": "GeneratedStmt", "expr": "GeneratedExpr", "expr_context": "GeneratedExprContext",
            "boolop": "GeneratedBoolop", "operator": "GeneratedOperator", "unaryop": "GeneratedUnaryop", "cmpop": "GeneratedCmpop",
            "excepthandler": "GeneratedExcepthandler", "pattern": "GeneratedPattern", "type_ignore": "GeneratedTypeIgnore",
            "type_param": "GeneratedTypeParam"}
SEQ = {"stmt": "Stmt", "expr": "Expr", "comprehension": "Comprehension", "excepthandler": "Excepthandler", "arg": "Arg",
       "keyword": "Keyword", "alias": "Alias", "withitem": "Withitem", "match_case": "MatchCase", "pattern": "Pattern",
       "type_ignore": "TypeIgnore", "type_param": "TypeParam", "identifier": "Identifier", "cmpop": "Cmpop"}


def pascal(name):
    return "".join(part[:1].upper() + part[1:] for part in name.split("_"))


def cls(name):
    return CLASS_NAMES.get(name, "Generated" + name)


def type_class(name):
    return SUM_BASE.get(name, "Generated" + pascal(name))


def field_name(owner, field):
    if owner == "arg" and field.name == "arg":
        return "Arg"
    if owner == "TypeIgnore":
        return {"lineno": "Lineno", "tag": "Tag"}[field.name]
    return pascal(field.name)


def to_py(expr, field):
    if field.type == "identifier":
        return f"Identifier({expr})"
    if field.type == "string":
        return f"Str({expr})"
    if field.type == "int":
        return f"Int({expr})"
    if field.type == "constant":
        return f"ConstantObject({expr})"
    return f"Convert({expr})"


def from_py(value, field, where):
    t = field.type
    if t == "identifier":
        return f"ToIdentifier({value})"
    if t == "string":
        return f"ToStr({value})"
    if t == "int":
        return f"ToOptionalInt({value})" if field.opt else f"ToInt({value}, \"{field.name}\")"
    if t == "constant":
        return f"ToConstant({value})"
    return f"({type_class(t)}?)ToNode({value})"


def gen_python(mod):
    out = ['"""Node classes of the abstract syntax tree. Generated by tools/gen_ast_module.py from Python.asdl."""',
           "",
           "PyCF_ONLY_AST = 1024",
           "PyCF_TYPE_COMMENTS = 4096",
           "PyCF_ALLOW_TOP_LEVEL_AWAIT = 8192",
           "",
           "",
           "class AST:",
           "    _fields = ()",
           "    _attributes = ()",
           "    __match_args__ = ()",
           "",
           "    def __init__(self, *args, **kwargs):",
           "        fields = type(self)._fields",
           "        if args:",
           "            if len(args) > len(fields):",
           "                raise TypeError(\"%s constructor takes at most %d positional argument%s\" % (",
           "                    type(self).__name__, len(fields), \"\" if len(fields) == 1 else \"s\"))",
           "            for name, value in zip(fields, args):",
           "                setattr(self, name, value)",
           "        for name, value in kwargs.items():",
           "            if name in fields[:len(args)]:",
           "                raise TypeError(\"%s got multiple values for argument %r\" % (type(self).__name__, name))",
           "            setattr(self, name, value)",
           "",
           "    def __reduce__(self):",
           "        return (type(self), (), self.__dict__)",
           "",
           ]
    for dfn in mod.dfns:
        value = dfn.value
        name = dfn.name
        attrs = tuple(a.name for a in value.attributes)
        if isinstance(value, asdl.Sum):
            out += ["", f"class {name}(AST):", f"    _attributes = {attrs!r}"]
            if any(a.opt for a in value.attributes):
                out += ["    end_lineno = None", "    end_col_offset = None"]
            out.append("")
            for ctor in value.types:
                fields = tuple(f.name for f in ctor.fields)
                out += ["", f"class {ctor.name}({name}):", f"    _fields = {fields!r}", f"    __match_args__ = {fields!r}"]
                for f in ctor.fields:
                    if f.opt:
                        out.append(f"    {f.name} = None")
                out.append("")
        else:
            fields = tuple(f.name for f in value.fields)
            out += ["", f"class {name}(AST):", f"    _fields = {fields!r}", f"    __match_args__ = {fields!r}",
                    f"    _attributes = {attrs!r}"]
            for f in value.fields:
                if f.opt:
                    out.append(f"    {f.name} = None")
            if any(a.opt for a in value.attributes):
                out += ["    end_lineno = None", "    end_col_offset = None"]
            out.append("")
    out += ["", "class slice(expr):", '    """Deprecated AST node class."""', "", "",
            "class Num(Constant):", "    pass", "", "", "class Str(Constant):", "    pass", "", "",
            "class Bytes(Constant):", "    pass", "", "", "class NameConstant(Constant):", "    pass", "", "",
            "class Ellipsis(Constant):", "    pass", "", "",
            "# make_type: the node classes are made in the ast module.",
            "for _node in list(globals().values()):",
            "    if isinstance(_node, type) and issubclass(_node, AST):",
            "        _node.__module__ = 'ast'",
            "del _node", ""]
    return "\n".join(out[:0] + out)


def gen_csharp(mod):
    to = []
    back = []

    def emit_to(owner, node_var, fields, attrs, name):
        to.append(f'                case {cls(name) if owner is None else "Generated" + pascal(owner)} {node_var}:')
        to.append(f'                {{')
        to.append(f'                    var o = New("{name if owner is None else owner}");')
        for f in fields:
            prop = field_name(owner or name, f)
            value = f"{node_var}.{prop}"
            if f.seq:
                conv = f"Seq({value}, item => {to_py('item', f) if f.type not in ('identifier',) else 'Identifier((GeneratedIdentifier)item)'})" \
                    if f.type == "identifier" else f"Seq({value})"
            else:
                conv = to_py(value, f)
            to.append(f'                    o.SetAttribute("{f.name}", {conv});')
        for a in attrs:
            prop = {"lineno": "LineNo", "col_offset": "ColOffset", "end_lineno": "EndLineNo", "end_col_offset": "EndColOffset"}[a.name]
            to.append(f'                    o.SetAttribute("{a.name}", PyInt.From({node_var}.{prop}));')
        to.append(f'                    return o;')
        to.append(f'                }}')

    def emit_back(owner, fields, attrs, name, kind):
        to_name = "Generated" + pascal(owner) if owner else cls(name)
        back.append(f'                case "{owner or name}":')
        back.append(f'                {{')
        back.append(f'                    var n = new {to_name}();')
        # obj2ast_<kind>: the attributes (lineno, ...) are read before the constructor's fields.
        if attrs:
            back.append(f'                    Locate(n, o, "{kind}");')
        for f in fields:
            prop = field_name(owner or name, f)
            if f.seq:
                # A sequence field that is missing is an empty list.
                attr = f'SeqField(o, "{f.name}")'
                seq = "Generated" + SEQ.get(f.type, pascal(f.type)) + "Seq"
                fill = "FillIdentifiers" if f.type == "identifier" else "Fill"
                back.append(f'                    n.{prop} = {fill}(new {seq}(), {attr}, "{owner or name}", "{f.name}");')
            else:
                attr = f'Field(o, "{f.name}", {"true" if f.opt else "false"}, "{owner or name}")'
                back.append(f'                    n.{prop} = {from_py(attr, f, name)};')
        back.append(f'                    return n;')
        back.append(f'                }}')

    for dfn in mod.dfns:
        value = dfn.value
        if isinstance(value, asdl.Sum):
            if all(not c.fields for c in value.types):
                for ctor in value.types:
                    to.append(f'                case {cls(ctor.name)}:')
                    to.append(f'                    return Singleton("{ctor.name}");')
                    back.append(f'                case "{ctor.name}":')
                    back.append(f'                    return {cls(ctor.name)}.Instance;')
                continue
            for ctor in value.types:
                emit_to(None, "n", ctor.fields, value.attributes, ctor.name)
                emit_back(None, ctor.fields, value.attributes, ctor.name, dfn.name)
        else:
            emit_to(dfn.name, "n", value.fields, value.attributes, dfn.name)
            emit_back(dfn.name, value.fields, value.attributes, dfn.name, dfn.name)
    return """// Generated by tools/gen_ast_module.py from Parser/Python.asdl. Do not edit.
using SharpPy.Generated;

namespace SharpPy
{
    public sealed partial class PythonAst
    {
        private PyObject Node(GeneratedPtr node)
        {
            switch (node)
            {
""" + "\n".join(to).replace("case Generatedn", "case Generated") + """
            }
            throw new System.InvalidOperationException($"no AST class for {node.GetType().Name}");
        }

        private GeneratedPtr Build(PyObject o, string kind)
        {
            switch (kind)
            {
""" + "\n".join(back) + """
            }
            throw PyTypeError.Create($"expected some sort of AST node, but got {o.ToRepr().Value}");
        }
    }
}
"""


def main():
    mod = asdl.parse(os.path.join(CPYTHON, "Parser", "Python.asdl"))
    with open(os.path.join(ROOT, "Lib", "_ast.py"), "w", encoding="utf-8", newline="\n") as f:
        f.write(gen_python(mod))
    with open(os.path.join(ROOT, "runtime", "compiler", "PythonAst.g.cs"), "w", encoding="utf-8", newline="\n") as f:
        f.write(gen_csharp(mod))


if __name__ == "__main__":
    main()
