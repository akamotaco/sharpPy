"""core/UnicodeTypeData.g.cs: CPython 3.12's Objects/unicodetype_db.h, the table unicodectype.c reads.

The _PyUnicode_TypeRecords (upper, lower, title, decimal, digit, flags), _PyUnicode_ExtendedCase,
the two-level index (index1, index2, SHIFT) and the code points of the generated
_PyUnicode_IsWhitespace and _PyUnicode_IsLinebreak switches are taken from the header as they
are, so str.isalpha(), str.upper() and the others answer from CPython's own data.
"""
import base64
import os
import re
import struct
import textwrap
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, "..", "cpython-v3.12.15", "Objects", "unicodetype_db.h")
OUTPUT = os.path.join(ROOT, "core", "UnicodeTypeData.g.cs")


def array(source, name):
    match = re.search(r"\b" + name + r"\[\] = \{(.*?)\};", source, re.S)
    return [int(value, 0) for value in re.findall(r"0x[0-9A-Fa-f]+|\d+", match.group(1))]


def switch(source, function):
    start = source.index(function + "(const Py_UCS4 ch)")
    body = source[start:source.index("return 0;", start)]
    return [int(value, 16) for value in re.findall(r"case 0x([0-9A-Fa-f]+):", body)]


def packed(values):
    raw = struct.pack("<%dH" % len(values), *values)
    packer = zlib.compressobj(9, zlib.DEFLATED, -15)
    return base64.b64encode(packer.compress(raw) + packer.flush()).decode("ascii")


def literal(name, text):
    chunks = textwrap.wrap(text, 110)
    return f"        internal const string {name} =\n" + " +\n".join(f'            "{chunk}"' for chunk in chunks) + ";\n"


def int_array(stream, name, values, per_line):
    stream.write(f"        internal static readonly int[] {name} =\n        {{\n")
    for i in range(0, len(values), per_line):
        stream.write("            " + ", ".join(str(v) for v in values[i:i + per_line]) + ",\n")
    stream.write("        };\n")


def main():
    source = open(HEADER, encoding="utf-8").read()
    records = re.search(r"_PyUnicode_TypeRecords\[\] = \{(.*?)\n\};", source, re.S).group(1)
    rows = [[int(v, 0) for v in fields.split(",")] for fields in re.findall(r"\{([^{}]*)\}", records)]
    assert all(len(row) == 6 for row in rows)
    extended = array(source, "_PyUnicode_ExtendedCase")
    shift = int(re.search(r"#define SHIFT (\d+)", source).group(1))
    index1 = array(source, "index1")
    index2 = array(source, "index2")
    whitespace = switch(source, "_PyUnicode_IsWhitespace")
    linebreak = switch(source, "_PyUnicode_IsLinebreak")
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as stream:
        stream.write("// Generated by tools/gen_unicode_type.py from CPython 3.12.15's Objects/unicodetype_db.h. Do not edit.\n")
        stream.write("namespace SharpPy\n{\n    internal static class UnicodeTypeData\n    {\n")
        stream.write(f"        internal const int Shift = {shift};\n")
        stream.write("        // _PyUnicode_TypeRecords, six ints a record: upper, lower, title, decimal, digit, flags\n")
        int_array(stream, "Records", [v for row in rows for v in row], 6)
        stream.write("        // _PyUnicode_ExtendedCase\n")
        int_array(stream, "ExtendedCase", extended, 16)
        stream.write("        // _PyUnicode_IsWhitespace and _PyUnicode_IsLinebreak\n")
        stream.write("        internal static readonly int[] Whitespace = { " + ", ".join(f"0x{c:04X}" for c in whitespace) + " };\n")
        stream.write("        internal static readonly int[] Linebreak = { " + ", ".join(f"0x{c:04X}" for c in linebreak) + " };\n")
        stream.write("        // index1 and index2, little-endian ushorts, raw deflate, base64\n")
        stream.write(literal("Index1", packed(index1)))
        stream.write(literal("Index2", packed(index2)))
        stream.write("    }\n}\n")
    print(len(rows), "records,", len(extended), "extended,", len(index1), "index1,", len(index2), "index2,",
          len(whitespace), "whitespace,", len(linebreak), "linebreak")


main()
