"""Generate core/ExceptionTable.g.cs from Objects/exceptions.c of CPython v3.12.15.

Each builtin exception is a static type made by one of three macros, which decide what type_ready
puts in its dict:
  SimpleExtendsException(BASE, NAME, DOC)       tp_init BaseException_init, tp_new BaseException_new
  MiddlingExtendsException(BASE, NAME, STORE, DOC)   tp_init STORE_init, no tp_new
  ComplexExtendsException(BASE, NAME, STORE, NEW, METHODS, MEMBERS, GETSET, STR, DOC)
                                                tp_init STORE_init, tp_new NEW, tp_str STR
The Unicode errors and MemoryError are written out as structs; they are read the same way.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / 'cpython-v3.12.15' / 'Objects' / 'exceptions.c'


def strip(name, suffix):
    name = name.strip()
    if name in ('0', 'NULL'):
        return None
    name = re.sub(r'/\*.*?\*/', '', name).strip()
    return name[:-len(suffix)] if name.endswith(suffix) else name


def main():
    text = SOURCE.read_text(encoding='utf-8')
    rows = []
    for m in re.finditer(r'^SimpleExtendsException\(\s*PyExc_\w+,\s*(\w+),', text, re.M):
        rows.append((m.group(1), 'BaseException', 'BaseException', None))
    for m in re.finditer(r'^MiddlingExtendsException\(\s*PyExc_\w+,\s*(\w+),\s*(\w+),', text, re.M):
        rows.append((m.group(1), m.group(2), None, None))
    for m in re.finditer(r'^ComplexExtendsException\(([^;]*?)\);', text, re.M | re.S):
        parts = [p.strip() for p in re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S).split(',')]
        # BASE, NAME, STORE, NEW, METHODS, MEMBERS, GETSET, STR, DOC
        rows.append((parts[1], parts[2], strip(parts[3], '_new'), strip(parts[7], '_str')))
    # The structs written out: tp_str, tp_init and tp_new by position in PyTypeObject.
    for name in ('UnicodeEncodeError', 'UnicodeDecodeError', 'UnicodeTranslateError', 'MemoryError'):
        body = re.search(r'PyTypeObject _PyExc_%s = \{(.*?)\};' % name, text, re.S).group(1)
        init = re.search(r'\(initproc\)(\w+)_init', body).group(1)
        new = re.search(r'\(initproc\)\w+, 0, (\w+)_new', body).group(1)
        str_ = re.search(r'\(reprfunc\)(\w+)_str', body)
        rows.append((name, init, new, str_.group(1) if str_ else None))
    rows.sort()

    def lit(value):
        return 'null' if value is None else f'"{value}"'

    lines = [f'            ("{n}", {lit(i)}, {lit(w)}, {lit(s)}),' for n, i, w, s in rows]
    out = '''// Generated by tools/gen_exception_table.py from Objects/exceptions.c of CPython v3.12.15. Do not edit.
namespace SharpPy
{
    internal static partial class PyExceptionTable
    {
        // (type, the struct whose _init is tp_init, the _new that is tp_new, the _str that is tp_str)
        private static readonly (string Name, string Init, string New, string Str)[] Types =
        {
%s
        };
    }
}
''' % '\n'.join(lines)
    (ROOT / 'core' / 'ExceptionTable.g.cs').write_text(out, encoding='utf-8')
    print(len(rows), 'types')


if __name__ == '__main__':
    main()
