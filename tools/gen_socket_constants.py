"""Generate modules/SocketModule.g.cs: the constants of CPython 3.12's _socket module (Windows build).

Modules/socketmodule.c socket_exec adds them with PyModule_AddIntMacro from the Winsock headers
(ws2def.h, ws2ipdef.h, mstcpip.h, hvsocket.h), under #ifdef, so neither the names a build has nor
their values are in the C source; this tool reads both from the reference CPython it runs on
(Windows), in socket_exec's insertion order.

usage: python tools/gen_socket_constants.py
"""
import os
import sys
import _socket

if sys.platform != "win32":
    raise SystemExit("run this with the Windows reference CPython")

constants = [(name, value) for name, value in vars(_socket).items()
             if not name.startswith('_') and type(value) is int]
texts = [(name, value) for name, value in vars(_socket).items()
         if not name.startswith('_') and type(value) is str]


def cs(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


lines = [
    "// Generated by tools/gen_socket_constants.py from CPython 3.12's _socket (Modules/socketmodule.c,",
    "// Windows build). Do not edit.",
    "namespace SharpPy.Modules",
    "{",
    "    internal static partial class SocketModule",
    "    {",
    "        // socket_exec: PyModule_AddIntMacro / ADD_INT_CONST, in insertion order.",
    "        private static readonly (string Name, long Value)[] IntConstants =",
    "        {",
]
for name, value in constants:
    lines.append(f'            ("{name}", {value}),')
lines += [
    "        };",
    "",
    "        // socket_exec: PyModule_AddStringConstant (BDADDR_*, HV_GUID_*).",
    "        private static readonly (string Name, string Value)[] TextConstants =",
    "        {",
]
for name, value in texts:
    lines.append(f'            ("{name}", {cs(value)}),')
lines += ["        };", "    }", "}", ""]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
target = os.path.join(root, "modules", "SocketModule.g.cs")
with open(target, "w", encoding="utf-8", newline="\n") as stream:
    stream.write("\n".join(lines))
print(target, len(constants), "int constants,", len(texts), "str constants")
