"""Generate modules/cjk/CjkMappings.g.cs from CPython 3.12's Modules/cjkcodecs/mappings_*.h.

Every table of the headers is kept as it is there, by its own name: the flat arrays (ucs2_t,
DBCHAR, Py_UCS4, unsigned char), the 256-entry indexes over them (dbcs_index, unim_index,
widedbcs_index: an offset into the array, bottom and top), pair_encodemap and gb18030's
ranges. U, N, M and D are cjkcodecs.h's UNIINV, NOCHAR, MULTIC and DBCINV. One blob per
header, zlib-compressed and base64-encoded; modules/cjk/CjkTables.cs reads it.

Blob layout, little-endian: a count, then per table its name (a byte length and ASCII), a
kind byte and its data -
  1 u16 array, 2 u32 array, 3 u8 array: int32 count and the values;
  4 index: the name of the array and 256 entries of int32 offset (-1 for none), bottom, top;
  5 pairs: int32 count and (u32 uniseq, u16 code);
  6 ranges: int32 count and (u32 first, u32 last, u16 base).

usage: python tools/gen_cjk_mappings.py <cpython Modules/cjkcodecs>
"""
import base64
import os
import re
import struct
import sys
import zlib

SYMBOLS = {"U": 0xFFFE, "N": 0xFFFF, "M": 0xFFFE, "D": 0xFFFD}
KINDS = {"ucs2_t": 1, "DBCHAR": 1, "Py_UCS4": 2, "unsigned char": 3}
HEADERS = {
    "Kr": ["mappings_kr.h"],
    "Jp": ["mappings_jp.h", "mappings_jisx0213_pair.h"],
    "Cn": ["mappings_cn.h"],
    "Tw": ["mappings_tw.h"],
    "Hk": ["mappings_hk.h"],
}
DECL = re.compile(r"static const (struct \w+|ucs2_t|DBCHAR|Py_UCS4|unsigned char)\s*(?:\{[^}]*\})?\s*(\w+)\s*\[[^\]]*\]\s*=\s*\{(.*?)\};", re.S)


def value(token):
    token = token.strip()
    return SYMBOLS[token] if token in SYMBOLS else int(token, 0)


def name_bytes(name):
    return bytes([len(name)]) + name.encode("ascii")


def tables(source):
    # mappings_jisx0213_pair.h: the definitions, not the EXTERN_JISX0213_PAIR declarations.
    source = re.sub(r"#ifdef EXTERN_JISX0213_PAIR.*?#else", "", source, flags=re.S)
    source = re.sub(r"//[^\n]*", "", source)
    for match in DECL.finditer(source):
        ctype, name, body = match.group(1), match.group(2), match.group(3)
        body = re.sub(r"\s+", "", body)
        if ctype in KINDS:
            values = [value(t) for t in body.split(",") if t]
            fmt = {1: "H", 2: "I", 3: "B"}[KINDS[ctype]]
            yield name, bytes([KINDS[ctype]]) + struct.pack("<i", len(values)) + struct.pack("<%d%s" % (len(values), fmt), *values)
            continue
        entries = re.findall(r"\{([^{}]*)\}", body)
        if ctype in ("struct dbcs_index", "struct unim_index", "struct widedbcs_index"):
            assert len(entries) == 256, (name, len(entries))
            array = None
            data = b""
            for entry in entries:
                pointer, bottom, top = entry.split(",")
                if pointer == "0":
                    data += struct.pack("<iBB", -1, 0, 0)
                    continue
                base, offset = pointer.split("+")
                assert array in (None, base), (name, base)
                array = base
                data += struct.pack("<iBB", int(offset), int(bottom), int(top))
            yield name, bytes([4]) + name_bytes(array or "") + data
        elif ctype == "struct pair_encodemap":
            data = struct.pack("<i", len(entries))
            for entry in entries:
                uniseq, code = entry.split(",")
                data += struct.pack("<IH", value(uniseq), value(code))
            yield name, bytes([5]) + data
        elif ctype == "struct _gb18030_to_unibmp_ranges":
            data = struct.pack("<i", len(entries))
            for entry in entries:
                first, last, base = entry.split(",")
                data += struct.pack("<IIH", value(first), value(last), value(base))
            yield name, bytes([6]) + data
        else:
            raise ValueError(ctype)


def main():
    root = sys.argv[1]
    out = ["// Generated by tools/gen_cjk_mappings.py from CPython 3.12.15 Modules/cjkcodecs/mappings_*.h.",
           "namespace SharpPy.Modules.Cjk",
           "{",
           "    internal static class CjkMappings",
           "    {"]
    for locale, headers in HEADERS.items():
        found = []
        for header in headers:
            source = open(os.path.join(root, header), encoding="utf-8").read()
            found.extend(tables(source))
        blob = struct.pack("<i", len(found)) + b"".join(name_bytes(n) + d for n, d in found)
        text = base64.b64encode(zlib.compress(blob, 9)).decode("ascii")
        out.append("        // %s: %s" % (", ".join(headers), ", ".join(n for n, _ in found)))
        out.append('        internal const string %s = "%s";' % (locale, text))
        print(locale, len(found), "tables,", len(blob), "bytes,", len(text), "base64")
    out += ["    }", "}", ""]
    target = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "modules", "cjk", "CjkMappings.g.cs")
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8", newline="\n") as stream:
        stream.write("\n".join(out))
    print(target)


main()
