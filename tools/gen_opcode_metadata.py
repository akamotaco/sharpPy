"""Generate runtime/OpcodeMetadata.g.cs from Python/opcode_metadata.h of CPython v3.12.15:
_PyOpcode_num_popped and _PyOpcode_num_pushed, which stack_effect reads.
"""
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = Path(os.environ.get("CPYTHON_SOURCE", ROOT.parent / "cpython-v3.12.15")) / "Python" / "opcode_metadata.h"


def cases(text, name):
    start = text.index(f"\n{name}(int opcode, int oparg, bool jump) {{")
    end = text.index("\n}\n", start)
    body = text[start:end]
    result = {}
    pending = []
    for line in body.split("\n"):
        line = line.strip()
        match = re.match(r"case (\w+):", line)
        if match:
            pending.append(match.group(1))
            continue
        match = re.match(r"return (.*);", line)
        if match and pending:
            for op in pending:
                result[op] = match.group(1)
            pending = []
    return result


def csharp(expression):
    expression = expression.replace("FVS_MASK", "4").replace("FVS_HAVE_SPEC", "4")
    # C reads an int as a truth value
    return re.sub(r"\(\(oparg & (\w+)\) \? ", r"(((oparg & \1) != 0) ? ", expression)


def main():
    text = HEADER.read_text(encoding="utf-8")
    enum = (ROOT / "runtime" / "PyBytecode.cs").read_text(encoding="utf-8")
    known = {m.group(1) for m in re.finditer(r"^\s*(\w+) = (\d+),", enum, re.M) if int(m.group(2)) < 256}
    parts = []
    for name, method in (("_PyOpcode_num_popped", "NumPopped"), ("_PyOpcode_num_pushed", "NumPushed")):
        table = cases(text, name)
        lines = [f"                case ByteCodeOp.{op}: return {csharp(value)};" for op, value in table.items() if op in known]
        parts.append(f'''        internal static int {method}(ByteCodeOp opcode, int oparg, bool jump)
        {{
            switch (opcode)
            {{
{chr(10).join(lines)}
                default: return -1;
            }}
        }}
''')
    output = '''// Generated by tools/gen_opcode_metadata.py from Python/opcode_metadata.h of CPython v3.12.15. Do not edit.
namespace SharpPy
{
    internal static class OpcodeMetadata
    {
%s    }
}
''' % "\n".join(parts)
    (ROOT / "runtime" / "OpcodeMetadata.g.cs").write_text(output, encoding="utf-8")


if __name__ == "__main__":
    main()
