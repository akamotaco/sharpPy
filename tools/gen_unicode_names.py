"""Generate core/UnicodeNameData.cs from CPython's Modules/unicodename_db.h.

The header is what \\N{...} reads in CPython: names and aliases are decoded with
the phrasebook walk of _getucname (Modules/unicodedata.c). Hangul syllables and
CJK unified ideographs have no entry there; UnicodeNames.cs computes them as
_getcode does. Named sequences stay out, \\N does not accept them.

Usage: python tools/gen_unicode_names.py [cpython checkout]
"""
import base64
import os
import re
import sys
import zlib


def array(text, name):
    match = re.search(r"\b" + name + r"\[\] = \{(.*?)\};", text, re.S)
    return [int(n, 0) for n in re.findall(r"0x[0-9a-fA-F]+|\d+", match.group(1))]


def define(text, name):
    return int(re.search(r"#define " + name + r" (\d+)", text).group(1))


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else os.path.join("..", "cpython-v3.12.15")
    text = open(os.path.join(root, "Modules", "unicodename_db.h"), encoding="ascii").read()
    lexicon = array(text, "lexicon")
    lexicon_offset = array(text, "lexicon_offset")
    phrasebook = array(text, "phrasebook")
    offset1 = array(text, "phrasebook_offset1")
    offset2 = array(text, "phrasebook_offset2")
    aliases = array(text, "name_aliases")
    shift = define(text, "phrasebook_shift")
    short = define(text, "phrasebook_short")
    aliases_start = int(re.search(r"aliases_start = (0x[0-9a-f]+)", text).group(1), 16)

    def name_of(code):
        if code >> shift >= len(offset1):
            return None
        offset = offset2[(offset1[code >> shift] << shift) + (code & ((1 << shift) - 1))]
        if not offset:
            return None
        chars = []
        while True:
            word = phrasebook[offset] - short
            if word >= 0:
                word = (word << 8) + phrasebook[offset + 1]
                offset += 2
            else:
                word = phrasebook[offset]
                offset += 1
            if chars:
                chars.append(" ")
            w = lexicon_offset[word]
            while lexicon[w] < 128:
                chars.append(chr(lexicon[w]))
                w += 1
            chars.append(chr(lexicon[w] & 127))
            if lexicon[w] == 128:
                chars.pop()
                return "".join(chars)

    lines = []
    for code in range(aliases_start):  # aliases and named sequences live above it
        name = name_of(code)
        if name:
            lines.append("%X %s" % (code, name))
    for index, code in enumerate(aliases):
        lines.append("%X %s" % (code, name_of(aliases_start + index)))

    packed = zlib.compress("\n".join(lines).encode("ascii"), 9)[2:-4]  # raw deflate
    encoded = base64.b64encode(packed).decode("ascii")
    with open(os.path.join("core", "UnicodeNameData.cs"), "w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by tools/gen_unicode_names.py from CPython 3.12.15 Modules/unicodename_db.h.\n")
        out.write("namespace SharpPy\n{\n    internal static class UnicodeNameData\n    {\n")
        out.write('        internal const string Deflated = "%s";\n' % encoded)
        out.write("    }\n}\n")
    print(len(lines), "names,", len(encoded), "characters")


main()
