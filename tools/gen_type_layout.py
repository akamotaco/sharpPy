"""Generate core/TypeLayout.g.cs: the instance layout of the builtin types.

best_base, solid_base and compatible_for_assignment decide from tp_basicsize, tp_itemsize,
tp_dictoffset and tp_weaklistoffset; whether a type takes subclasses is Py_TPFLAGS_BASETYPE. SharpPy's instances have no such layout, so the numbers
of the static types come from the reference CPython 3.12 this tool runs on.
"""
import importlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

MODULES = """types collections functools itertools re io weakref array struct operator select
decimal datetime contextvars json pickle csv threading random time zlib os _md5 _sha1 _sha2 _sha3 _blake2""".split()

HEAPTYPE = 1 << 9
IMMUTABLETYPE = 1 << 8
HAVE_GC = 1 << 14
DISALLOW_INSTANTIATION = 1 << 7
BASETYPE = 1 << 10


def written_in_c(kind):
    module = sys.modules.get(kind.__module__)
    return module is not None and not str(getattr(module, '__file__', '') or '').endswith('.py')


def main():
    for name in MODULES:
        try:
            importlib.import_module(name)
        except ImportError:
            pass
    seen = set()
    stack = [object]
    while stack:
        kind = stack.pop()
        if kind in seen:
            continue
        seen.add(kind)
        stack.extend(type.__subclasses__(kind))
    rows = {}
    for kind in sorted(seen, key=lambda t: (t.__name__, t.__module__)):
        # A class written in Python; a C module's heap type (_io's, since 3.12) has a layout, and so
        # has one a .py module re-exports (functools.partial is _functools', os.stat_result is
        # posix'), which, unlike a class statement, a spec can make IMMUTABLETYPE or final.
        made_by_spec = kind.__flags__ & IMMUTABLETYPE or not kind.__flags__ & BASETYPE
        if kind.__flags__ & HEAPTYPE and not made_by_spec and not written_in_c(kind):
            continue
        rows.setdefault(kind.__name__, (kind.__basicsize__, kind.__itemsize__, kind.__dictoffset__,
                                        kind.__weakrefoffset__, bool(kind.__flags__ & HAVE_GC),
                                        bool(kind.__flags__ & DISALLOW_INSTANTIATION),
                                        not kind.__flags__ & BASETYPE,
                                        bool(kind.__flags__ & HEAPTYPE)))
    lines = [
        '// Generated by tools/gen_type_layout.py. Do not edit.',
        'using System.Collections.Generic;',
        '',
        'namespace SharpPy',
        '{',
        '    internal static partial class TypeLayouts',
        '    {',
        '        private static readonly Dictionary<string, TypeLayout> Table = new()',
        '        {',
    ]
    for name, (basic, item, dict_offset, weak, gc, closed, final, spec) in rows.items():
        flag = 'true' if gc else 'false'
        extra = (', NoInstances: true' if closed else '') + (', Final: true' if final else '') + (', Spec: true' if spec else '')
        lines.append(f'            ["{name}"] = new TypeLayout({basic}, {item}, {dict_offset}, {weak}, {flag}{extra}),')
    lines += ['        };', '    }', '}', '']
    (ROOT / 'core' / 'TypeLayout.g.cs').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(len(rows))


if __name__ == '__main__':
    main()
