"""core/ModuleDocs.g.cs: the m_doc of every module SharpPy implements natively.

The names are the keys of the native module table in core/PyModule.cs (_builtinModules), and
sys and builtins, which are made before it. Each is imported in CPython 3.12 and its __doc__
recorded; a module whose doc is None (PyModuleDef.m_doc NULL) is left out, and keeps None.
"""
import importlib
import os
import re
import sys


def literal(text):
    out = ['"']
    for ch in text:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\r':
            out.append('\\r')
        elif ch == '\t':
            out.append('\\t')
        elif ord(ch) < 0x20 or ord(ch) > 0x7e:
            out.append('\\u%04x' % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return ''.join(out)


def main():
    if sys.version_info[:2] != (3, 12):
        raise SystemExit("run with CPython 3.12")
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    source = open(os.path.join(root, "core", "PyModule.cs"), encoding="utf-8").read()
    start = source.index("_builtinModules = new Dictionary<string, Func<PyModule>>")
    end = source.index("};", start)
    names = set(re.findall(r'\["([A-Za-z0-9_.]+)"\]\s*=', source[start:end])) | {"sys", "builtins"}
    docs = {}
    for name in sorted(names):
        try:
            module = importlib.import_module(name)
        except ImportError:
            continue
        if module.__doc__ is not None:
            docs[name] = module.__doc__
    lines = [
        "// <auto-generated> tools/gen_module_docs.py from CPython " + sys.version.split()[0] + " </auto-generated>",
        "using System.Collections.Generic;",
        "",
        "namespace SharpPy",
        "{",
        "    internal static partial class PyDocs",
        "    {",
        "        // PyModuleDef.m_doc of the native modules; a module not listed has none.",
        "        internal static readonly Dictionary<string, string> ModuleDocs = new()",
        "        {",
    ]
    for name in sorted(docs):
        lines.append(f"            [{literal(name)}] = {literal(docs[name])},")
    lines += ["        };", "    }", "}", ""]
    with open(os.path.join(root, "core", "ModuleDocs.g.cs"), "w", encoding="utf-8", newline="\n") as stream:
        stream.write("\n".join(lines))
    print(len(docs), "module docs of", len(names), "modules")


main()
