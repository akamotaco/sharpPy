"""Generates modules/CmathModule.g.cs from CPython's Modules/cmathmodule.c: the function bodies and the
special value tables are C that reads the same in C#, so this keeps them identical to the source.

usage: python tools/gen_cmath.py ../cpython-v3.12.15/Modules/cmathmodule.c
"""
import re
import sys

source = open(sys.argv[1], encoding="utf-8").read()
source = re.sub(r"/\*.*?\*/", "", source, flags=re.S)
names = ["acos", "acosh", "asin", "asinh", "atan", "atanh", "cos", "cosh", "exp", "log10", "sin", "sinh", "sqrt", "tan",
         "tanh"]


def body_of(signature):
    start = source.index(signature)
    open_brace = source.index("{", start)
    depth, i = 0, open_brace
    while True:
        if source[i] == "{":
            depth += 1
        elif source[i] == "}":
            depth -= 1
            if depth == 0:
                return source[open_brace:i + 1]
        i += 1


def translate(body):
    body = re.sub(r"^#.*$", "", body, flags=re.M)
    body = body.replace("Py_complex", "Pair")
    body = re.sub(r"\berrno = (EDOM|ERANGE)", lambda m: "_errno = Fault." + ("Domain" if m[1] == "EDOM" else "Range"), body)
    body = body.replace("errno = 0", "_errno = Fault.None")
    body = body.replace("Py_IS_FINITE", "double.IsFinite").replace("Py_IS_INFINITY", "double.IsInfinity")
    body = body.replace("Py_IS_NAN", "double.IsNaN").replace("Py_HUGE_VAL", "double.PositiveInfinity")
    body = body.replace("Py_NAN", "double.NaN").replace("Py_MATH_PI", "Math.PI").replace("DBL_MAX", "double.MaxValue")
    body = re.sub(r"\bDBL_MIN\b", "DoubleMin", body).replace("(double)", "(double)")
    body = re.sub(r"SPECIAL_VALUE\(z, (\w+)\);", r"{ if (!double.IsFinite(z.Real) || !double.IsFinite(z.Imag)) { _errno = Fault.None; return \1[SpecialType(z.Real) * 7 + SpecialType(z.Imag)]; } }", body)
    body = re.sub(r"(\w+_special_values)\[special_type\((.+?)\)\]\s*\[special_type\((.+?)\)\]",
                  lambda m: f"{m[1]}[SpecialType({m[2]}) * 7 + SpecialType({m[3]})]", body, flags=re.S)
    body = body.replace("Py_MATH_E", "Math.E").replace("DBL_MANT_DIG", "53")
    body = body.replace("errno_save = errno;", "errno_save = _errno;").replace("errno = errno_save", "_errno = errno_save")
    body = body.replace("int errno_save", "Fault errno_save")
    body = re.sub(r"\.real\b", ".Real", body)
    body = re.sub(r"\.imag\b", ".Imag", body)
    for name in ("fabs", "sqrt", "log", "exp", "sin", "cos", "sinh", "cosh", "tanh", "atan2", "asinh", "atanh", "tan",
                 "floor", "acos", "asin"):
        body = re.sub(r"(?<![\w.])%s\(" % name, "Math.%s(" % ("Abs" if name == "fabs" else name.capitalize()), body)
    body = re.sub(r"(?<![\w.])Math\.Atan2\(", "Math.Atan2(", body)
    body = re.sub(r"(?<![\w.])copysign\(", "Math.CopySign(", body)
    body = re.sub(r"(?<![\w.])hypot\(", "Hypot(", body)
    body = re.sub(r"(?<![\w.])ldexp\(", "Math.ScaleB(", body)
    body = re.sub(r"(?<![\w.])m_log1p\(", "Log1p(", body)
    body = re.sub(r"(?<![\w.])_Py_c_abs\(", "Hypot2(", body)
    body = re.sub(r"(?<![\w.])m_atan2\(", "Atan2(", body)
    body = re.sub(r"(?<![\w.])m_log\(", "Math.Log(", body)
    for name in names:
        body = re.sub(r"(?<![\w.])cmath_%s_impl\(module, " % name, "%s(" % name.capitalize(), body)
    body = body.replace("c_atan2(", "CAtan2(").replace("c_log(", "CLog(")
    body = re.sub(r"Pair (\w+) = \{(.*?), (.*?)\};", r"Pair \1 = new Pair(\2, \3);", body)
    body = re.sub(r"Pair (\w+);", r"Pair \1 = default;", body)
    body = re.sub(r"Pair (\w+), (\w+);", r"Pair \1 = default, \2 = default;", body)
    body = re.sub(r"Pair (\w+), (\w+), (\w+);", r"Pair \1 = default, \2 = default, \3 = default;", body)
    body = re.sub(r"double (\w+), (\w+), (\w+), (\w+);", r"double \1 = 0, \2 = 0, \3 = 0, \4 = 0;", body)
    body = re.sub(r"double (\w+), (\w+), (\w+);", r"double \1 = 0, \2 = 0, \3 = 0;", body)
    body = re.sub(r"double (\w+), (\w+);", r"double \1 = 0, \2 = 0;", body)
    body = re.sub(r"double (\w+);", r"double \1 = 0;", body)
    body = body.replace("int ", "int ")
    body = body.replace("(Py_complex)", "")
    body = re.sub(r"(?<![\w.])(\d+)\.(?!\d)", lambda m: m[1] + ".0", body)
    return body


out = ["// Generated by tools/gen_cmath.py from Modules/cmathmodule.c. Do not edit.", "using System;", "",
       "namespace SharpPy.Modules", "{", "    internal static partial class CmathModule", "    {"]
for name in names:
    out.append(f"        private static Pair {name.capitalize()}(Pair z)")
    out.append(translate(body_of(f"cmath_{name}_impl(PyObject *module, Py_complex z)\n")))
out.append("        private static double CAtan2(Pair z)")
out.append(translate(body_of("c_atan2(Py_complex z)\n")))
out.append("        private static Pair CLog(Pair z)")
out.append(translate(body_of("c_log(Py_complex z)\n")))
for table in re.finditer(r"INIT_SPECIAL_VALUES\((\w+), \{(.*?)\}\)", source, flags=re.S):
    cells = re.findall(r"C\(([^,]+),\s*([^)]+)\)", table[2])
    assert len(cells) == 49, (table[1], len(cells))
    def value(text):
        text = text.strip()
        m = {"P": "Math.PI", "P14": "(0.25 * Math.PI)", "P12": "(0.5 * Math.PI)", "P34": "(0.75 * Math.PI)",
             "INF": "double.PositiveInfinity", "N": "double.NaN", "U": "-9.5426319407711027e33"}
        text = re.sub(r"(\d)\.$", lambda m: m[1] + ".0", text)
        return ("-" + m[text[1:]]) if text.startswith("-") and text[1:] in m else m.get(text, text)
    out.append(f"        private static readonly Pair[] {table[1]} =\n        {{")
    out.extend(f"            new Pair({value(a)}, {value(b)})," for a, b in cells)
    out.append("        };")
out += ["    }", "}", ""]
open("modules/CmathModule.g.cs", "w", encoding="utf-8", newline="\n").write("\n".join(out))
