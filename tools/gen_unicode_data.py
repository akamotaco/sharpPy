"""Write core/UnicodeProperties.g.cs: the properties of unicodedata, taken from CPython 3.12 itself.

Each property is its runs over the code space. Compositions are listed because the exclusions are
not visible in the decompositions: a pair composes only if NFC keeps the character that names it.
"""
import base64
import os
import sys
import textwrap
import unicodedata
import zlib

OUTPUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "core", "UnicodeProperties.g.cs")

PROPERTIES = (
    ("category", unicodedata.category),
    ("bidirectional", unicodedata.bidirectional),
    ("east_asian_width", unicodedata.east_asian_width),
    ("combining", unicodedata.combining),
    ("mirrored", unicodedata.mirrored),
    ("decimal", lambda c: unicodedata.decimal(c, "")),
    ("digit", lambda c: unicodedata.digit(c, "")),
    ("numeric", lambda c: unicodedata.numeric(c, "")),
    ("decomposition", unicodedata.decomposition),
)


def runs(function):
    last = object()
    for code in range(sys.maxunicode + 1):
        value = function(chr(code))
        if value != last:
            yield code, value
            last = value


def compositions():
    for code in range(sys.maxunicode + 1):
        parts = unicodedata.decomposition(chr(code)).split()
        if len(parts) == 2 and not parts[0].startswith("<") and unicodedata.normalize("NFC", chr(code)) == chr(code):
            yield code


def main():
    if unicodedata.unidata_version != "15.0.0":
        raise SystemExit("needs the Unicode version of CPython 3.12")
    lines = []
    for name, function in PROPERTIES:
        lines.append("=" + name)
        lines.extend(f"{code:x} {value!r}" if isinstance(value, float) else f"{code:x} {value}"
                     for code, value in runs(function))
    lines.append("=compositions")
    lines.extend(f"{code:x}" for code in compositions())
    packer = zlib.compressobj(9, zlib.DEFLATED, -15)
    packed = packer.compress("\n".join(lines).encode("ascii")) + packer.flush()
    text = base64.b64encode(packed).decode("ascii")
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as stream:
        stream.write("// Generated by tools/gen_unicode_data.py. Do not edit.\n")
        stream.write("namespace SharpPy\n{\n    internal static class UnicodePropertyData\n    {\n")
        stream.write("        internal const string Version = \"15.0.0\";\n")
        stream.write("        internal const string Deflated =\n")
        chunks = textwrap.wrap(text, 110)
        stream.write(" +\n".join(f'            "{chunk}"' for chunk in chunks))
        stream.write(";\n    }\n}\n")
    print(len(lines), "lines,", len(packed), "bytes packed")


main()
