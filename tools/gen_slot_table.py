"""Generate core/SlotTable.g.cs: which slots add_operators gives each builtin type, and the order of
each type's tp_dict as type_ready lays it out. The slots come in the order
add_operators put them in tp_dict (slotdefs order, wrapper-less entries skipped, the slot each type
actually fills). A slot CPython sets to None (PyObject_HashNotImplemented) is written "-name":
its place in the dict, no wrapper.

CPython fills tp_* in static tables and type_ready turns them into wrappers. SharpPy's
builtin types answer through CLR virtuals, so this table says which of them a type has.
Run with the reference CPython 3.12.
"""
import re
import sys
import types
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

SLOTS = """__repr__ __str__ __hash__ __eq__ __ne__ __lt__ __le__ __gt__ __ge__ __iter__ __next__
__len__ __contains__ __getitem__ __setitem__ __delitem__ __call__ __get__ __set__ __delete__
__getattribute__ __setattr__ __delattr__ __bool__ __neg__ __pos__ __abs__ __invert__ __int__ __float__
__index__ __add__ __radd__ __sub__ __rsub__ __mul__ __rmul__ __mod__ __rmod__ __divmod__ __rdivmod__
__pow__ __rpow__ __lshift__ __rlshift__ __rshift__ __rrshift__ __and__ __rand__ __xor__ __rxor__
__or__ __ror__ __floordiv__ __rfloordiv__ __truediv__ __rtruediv__ __iadd__ __imul__ __ior__
__await__ __aiter__ __anext__""".split()


def main():
    source = (ROOT / 'core' / 'PyType.cs').read_text(encoding='utf-8')
    fields = {m.group(2): m.group(1) for m in re.finditer(r'public static readonly PyType (\w+) = new PyType\("([^"]+)"', source)}
    fields['type'] = 'TypeType'
    kinds = [
        object, type, int, bool, float, complex, str, bytes, bytearray, memoryview, list, tuple, dict, set, frozenset,
        range, slice, property, staticmethod, classmethod, super, enumerate, map, filter, zip, reversed,
        BaseException, types.FunctionType, types.MethodType, types.ModuleType, types.GeneratorType, types.CoroutineType,
        types.AsyncGeneratorType, types.CodeType, types.FrameType, types.TracebackType, types.CellType,
        types.MappingProxyType, types.SimpleNamespace, types.GenericAlias,
        types.BuiltinFunctionType, types.WrapperDescriptorType, types.MethodWrapperType, types.MethodDescriptorType,
        types.GetSetDescriptorType, types.ClassMethodDescriptorType, types.MemberDescriptorType,
        type(iter([])), type(iter(())), type(iter({})), type(iter("")), type(iter(b"")), type(iter(set())), type(iter(range(1))),
        type({}.keys()), type({}.values()), type({}.items()),
    ]
    lines = []
    layout = []
    unknown = []
    for kind in kinds:
        names = [name if vars(kind)[name] is not None else '-' + name for name in vars(kind) if name in SLOTS]
        field = fields.get(kind.__name__)
        if field is None:
            unknown.append(kind.__name__)
            continue
        lines.append(f'            Add(PyType.{field}, "{" ".join(names)}");')
        layout.append(f'            Lay(PyType.{field}, "{" ".join(vars(kind))}");')
    if unknown:
        print('no field for', unknown, file=sys.stderr)
    # The static types of the C modules SharpPy has: type_ready gives them their wrappers when the
    # module readies them, keyed "<module>.<qualname>" as their tp_name reads.
    import importlib
    modules = ("array", "_io", "_collections", "itertools", "_functools", "_struct", "_thread", "_sre", "_csv",
               "_weakref", "_contextvars", "_operator", "_queue", "weakref", "_random", "_bisect", "_heapq")
    module_lines = []
    seen = set()
    for modname in modules:
        try:
            module = importlib.import_module(modname)
        except ImportError:
            continue
        for value in vars(module).values():
            if not isinstance(value, type) or value in seen or value.__module__ == 'builtins' or issubclass(value, BaseException):
                continue
            # A class written in Python has functions in its dict; a C type made from a spec does not.
            if any(isinstance(v, types.FunctionType) for v in vars(value).values()):
                continue
            seen.add(value)
            names = [name if vars(value)[name] is not None else '-' + name for name in vars(value) if name in SLOTS]
            module_lines.append(f'            ["{value.__module__}.{value.__qualname__}"] = "{" ".join(names)}",')
    text = '''// Generated by tools/gen_slot_table.py from the tables of CPython 3.12. Do not edit.
namespace SharpPy
{
    internal static partial class PySlotWrappers
    {
        private static void AddAll()
        {
%s
        }

        // add_operators of the C modules' static types, by "<module>.<qualname>".
        private static readonly System.Collections.Generic.Dictionary<string, string> ModuleSlots = new()
        {
%s
        };

        // type_ready's tp_dict of each type, in order: __new__, add_operators, the methods, members
        // and getsets, __doc__ (type_ready_fill_dict).
        private static void LayAll()
        {
%s
        }
    }
}
''' % ('\n'.join(lines), '\n'.join(sorted(module_lines)), '\n'.join(layout))
    (ROOT / 'core' / 'SlotTable.g.cs').write_text(text, encoding='utf-8')


if __name__ == '__main__':
    main()
