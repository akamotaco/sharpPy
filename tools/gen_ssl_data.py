"""Generate modules/Ssl/SslData.g.cs: the OpenSSL tables CPython 3.12's _ssl reads through libssl and
libcrypto, taken from the reference CPython's OpenSSL (3.x, Windows build) through _ssl itself.

- The ASN.1 object table (crypto/objects/obj_dat.h): every NID with its short name, long name and OID,
  as _ssl.nid2obj reports them. txt2obj, nid2obj, OBJ_obj2txt and the cipher dicts' "symmetric",
  "digest", "kea" and "auth" long names read it.
- The TLS cipher table (ssl/s3_lib.c ssl3_ciphers and the TLS 1.3 suites): every cipher the build has,
  in the order ssl_create_cipher_list arranges them before it reads a rule string (the order
  "ALL:COMPLEMENTOFALL" lists them), with SSL_CIPHER_description, the bits, and the strength classes
  (algo_strength: HIGH, MEDIUM, FIPS, NOT_DEFAULT) read back as the aliases select them.

usage: python tools/gen_ssl_data.py
"""
import os
import ssl
import sys
import _ssl

if sys.platform != "win32":
    raise SystemExit("run this with the Windows reference CPython")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "modules", "Ssl", "SslData.g.cs")

objects = []
for nid in range(1, 4000):
    try:
        objects.append(_ssl.nid2obj(nid))
    except ValueError:
        pass


def names(rule):
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    context.set_ciphers(rule + ":@SECLEVEL=0")
    return {c["name"] for c in context.get_ciphers() if c["protocol"] != "TLSv1.3"}


context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
context.set_ciphers("ALL:COMPLEMENTOFALL:@SECLEVEL=0")
ciphers = context.get_ciphers()
high, medium, fips, not_default = names("HIGH"), names("MEDIUM"), names("FIPS"), names("COMPLEMENTOFDEFAULT")


def ordered(rule):
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    try:
        context.set_ciphers(rule + ":@SECLEVEL=0")
    except ssl.SSLError:
        return []
    return [c["name"] for c in context.get_ciphers() if c["protocol"] != "TLSv1.3"]


# "ALL:COMPLEMENTOFALL" puts the eNULL ciphers after the rest; one ADD rule keeps the starting order of
# what it selects, so the starting order is the one every single-alias selection agrees with
# (a topological merge of them, ties in the "ALL:COMPLEMENTOFALL" order).
rank = {c["name"]: i for i, c in enumerate(ciphers) if c["protocol"] != "TLSv1.3"}
lists = [ordered("ALL"), ordered("COMPLEMENTOFALL")] + [ordered(alias) for alias in (
    "kRSA", "kDHE", "kECDHE", "kPSK", "kRSAPSK", "kECDHEPSK", "kDHEPSK", "kSRP", "aRSA", "aDSS", "aNULL", "aECDSA",
    "aPSK", "aSRP", "MD5", "SHA1", "SHA256", "SHA384", "SSLv3", "TLSv1", "TLSv1.2", "HIGH", "MEDIUM", "FIPS",
    "COMPLEMENTOFDEFAULT", "CBC", "AES", "CAMELLIA", "ARIA", "CHACHA20", "AESCCM")]
after = {name: set() for name in rank}
for order in lists:
    for a, b in zip(order, order[1:]):
        after[b].add(a)
tls12 = []
pending = set(n for n in rank if n in after)
import heapq
heap = [(rank[n], n) for n in pending if not (after[n] & pending)]
heapq.heapify(heap)
done = set()
while heap:
    _, n = heapq.heappop(heap)
    if n in done:
        continue
    done.add(n)
    tls12.append(n)
    for m in pending - done:
        if n in after[m] and not (after[m] - done) and m not in [h[1] for h in heap]:
            heapq.heappush(heap, (rank[m], m))
by_name = {c["name"]: c for c in ciphers}
ciphers = [c for c in ciphers if c["protocol"] == "TLSv1.3"] + [by_name[n] for n in tls12]
assert len(ciphers) == len(by_name), (len(ciphers), len(by_name))


def cs(value):
    if value is None:
        return "null"
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


lines = [
    "// Generated by tools/gen_ssl_data.py from the reference CPython 3.12's _ssl and its OpenSSL. Do not edit.",
    "namespace SharpPy.Modules.Ssl",
    "{",
    "    internal static partial class SslData",
    "    {",
    "        // obj_dat.h: nid, sn, ln, OID (null for an object without one).",
    "        internal static readonly (int Nid, string Sn, string Ln, string Oid)[] Objects =",
    "        {",
]
for nid, sn, ln, oid in objects:
    lines.append(f"            ({nid}, {cs(sn)}, {cs(ln)}, {cs(oid)}),")
lines += [
    "        };",
    "",
    "        // ssl3_ciphers and the TLS 1.3 suites, in ssl_create_cipher_list's starting order:",
    "        // id, name, protocol, SSL_CIPHER_description, strength_bits, alg_bits, aead, symmetric, digest,",
    "        // kea, auth, and algo_strength (H = HIGH, M = MEDIUM, F = FIPS, N = NOT_DEFAULT).",
    "        internal static readonly (uint Id, string Name, string Protocol, string Description, int StrengthBits,",
    "            int AlgBits, bool Aead, string Symmetric, string Digest, string Kea, string Auth, string Strength)[] Ciphers =",
    "        {",
]
for c in ciphers:
    flags = "".join(f for f, s in (("H", high), ("M", medium), ("F", fips), ("N", not_default)) if c["name"] in s)
    lines.append(f"            (0x{c['id']:08X}, {cs(c['name'])}, {cs(c['protocol'])}, {cs(c['description'])}, "
                 f"{c['strength_bits']}, {c['alg_bits']}, {'true' if c['aead'] else 'false'}, {cs(c['symmetric'])}, "
                 f"{cs(c['digest'])}, {cs(c['kea'])}, {cs(c['auth'])}, {cs(flags)}),")
lines += ["        };", "    }", "}", ""]
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", encoding="utf-8", newline="\n") as stream:
    stream.write("\n".join(lines))
print(OUT, len(objects), "objects,", len(ciphers), "ciphers")
