"""Generate modules/AstModule.g.cs from CPython 3.12's Python/Python-ast.c.

init_types there makes the node classes: make_type(name, base, fields, doc) - a call of type()
with _fields, __match_args__, __module__ 'ast' and __doc__ -, add_attributes, the class attributes
set to None for optional fields and attributes, and the singletons of the classes without fields
(Load, Add, ...). astmodule_exec puts AST, the PyCF_* constants and the classes in the module in
its own order. Those are literal C, which this tool reads and writes out as the same calls in
the same order, for modules/AstModule.cs to run.

usage: python tools/gen_ast_types.py <cpython Python/Python-ast.c>
"""
import ast
import os
import re
import sys

source = open(sys.argv[1], encoding="utf-8").read()


def body(header):
    start = source.index(header)
    end = source.index("\n}\n", start)
    return source[start:end]


def c_strings(text):
    """The value of adjacent C string literals."""
    return "".join(ast.literal_eval('"' + s + '"') for s in re.findall(r'"((?:[^"\\]|\\.)*)"', text))


arrays = {}
for name, items in re.findall(r"static const char \* const (\w+)\[\]\s*=\s*\{(.*?)\};", source, re.S):
    arrays[name] = re.findall(r'"([^"]*)"', items)

steps = []
init = body("\ninit_types(struct ast_state *state)")
# One statement per ';' (no string literal of init_types holds one); the C strings keep their spaces.
for raw in init.split(";"):
    statement = raw.strip()
    match = re.search(r'state->(\w+)_type\s*=\s*make_type\(state,\s*"(\w+)",\s*state->(\w+)_type,\s*(\w+),\s*(\d+),\s*(.*)\)$', statement, re.S)
    if match:
        name, label, base, fields, count, doc = match.groups()
        assert name == label
        names = [] if fields == "NULL" else arrays[fields]
        assert len(names) == int(count), (name, names, count)
        steps.append(("Make", name, base, names, c_strings(doc)))
        continue
    match = re.search(r"add_attributes\(state,\s*state->(\w+)_type,\s*(\w+),\s*(\d+)\)", statement)
    if match:
        name, attributes, count = match.groups()
        names = [] if attributes == "NULL" else arrays[attributes]
        assert len(names) == int(count)
        steps.append(("Attributes", name, names))
        continue
    match = re.search(r"PyObject_SetAttr\(state->(\w+)_type,\s*state->(\w+),\s*Py_None\)", statement)
    if match:
        steps.append(("None", match.group(1), match.group(2)))
        continue
    match = re.search(r"state->(\w+)_singleton\s*=\s*PyType_GenericNew\(\(PyTypeObject\s*\*\)\s*state->(\w+)_type", statement)
    if match:
        assert match.group(1) == match.group(2)
        steps.append(("Singleton", match.group(1)))
        continue
    assert ("make_type" not in statement and "add_attributes" not in statement and "SetAttr" not in statement
            and "_singleton =" not in statement), statement

exports = []
for statement in re.sub(r"\s+", " ", body("\nastmodule_exec(PyObject *m)")).split(";"):
    match = re.search(r'PyModule_AddObjectRef\(m, "(\w+)", state->(\w+)_type\)', statement)
    if match:
        exports.append(match.group(1))
        continue
    match = re.search(r"PyModule_AddIntMacro\(m, (\w+)\)", statement)
    if match:
        exports.append(match.group(1))


def cs(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def cs_array(names):
    return "new string[] { " + ", ".join(cs(n) for n in names) + " }" if names else "System.Array.Empty<string>()"


lines = [
    "// Generated by tools/gen_ast_types.py from CPython 3.12's Python/Python-ast.c (init_types, astmodule_exec).",
    "namespace SharpPy.Modules",
    "{",
    "    internal static partial class AstModule",
    "    {",
    "        // init_types",
    "        private static void InitTypes()",
    "        {",
]
for step in steps:
    kind = step[0]
    if kind == "Make":
        _, name, base, names, doc = step
        lines.append(f"            MakeType({cs(name)}, {cs(base)}, {cs_array(names)}, {cs(doc)});")
    elif kind == "Attributes":
        lines.append(f"            AddAttributes({cs(step[1])}, {cs_array(step[2])});")
    elif kind == "None":
        lines.append(f"            SetNone({cs(step[1])}, {cs(step[2])});")
    else:
        lines.append(f"            MakeSingleton({cs(step[1])});")
lines += [
    "        }",
    "",
    "        // astmodule_exec: what the module holds, in order.",
    "        private static readonly string[] Exported =",
    "        {",
]
for i in range(0, len(exports), 6):
    lines.append("            " + " ".join(cs(n) + "," for n in exports[i:i + 6]))
lines += ["        };", "    }", "}", ""]

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
target = os.path.join(root, "modules", "AstModule.g.cs")
with open(target, "w", encoding="utf-8", newline="\n") as stream:
    stream.write("\n".join(lines))
print(target, len(steps), "steps,", len(exports), "names")
