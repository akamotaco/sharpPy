"""Generate modules/WinapiModule.g.cs: the names of CPython 3.12's _winapi module.

Modules/_winapi.c adds its constants with WINAPI_CONSTANT from the Windows headers, so their
values are not in the C source; this tool reads them, and the names of its functions, from the
reference CPython it runs on (on Windows).

usage: python tools/gen_winapi_constants.py
"""
import os
import _winapi

constants = sorted(name for name, value in vars(_winapi).items()
                   if not name.startswith('_') and type(value) is int)
texts = sorted(name for name, value in vars(_winapi).items()
               if not name.startswith('_') and (type(value) is str or value is None))
functions = sorted(name for name, value in vars(_winapi).items()
                   if not name.startswith('_') and type(value).__name__ == 'builtin_function_or_method')


def cs(value):
    return 'null' if value is None else '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


lines = [
    "// Generated by tools/gen_winapi_constants.py from CPython 3.12's _winapi (Modules/_winapi.c). Do not edit.",
    "namespace SharpPy.Modules",
    "{",
    "    internal static partial class WinapiModule",
    "    {",
    "        // WINAPI_CONSTANT, as decimal text: some do not fit a long (INVALID_HANDLE_VALUE).",
    "        private static readonly (string Name, string Value)[] Constants =",
    "        {",
]
for name in constants:
    lines.append(f'            ("{name}", "{getattr(_winapi, name)}"),')
lines += [
    "        };",
    "",
    "        // The str constants (LOCALE_NAME_*); null is None.",
    "        private static readonly (string Name, string Value)[] TextConstants =",
    "        {",
]
for name in texts:
    lines.append(f'            ("{name}", {cs(getattr(_winapi, name))}),')
lines += [
    "        };",
    "",
    "        // winapi_functions",
    "        private static readonly string[] Functions =",
    "        {",
]
for i in range(0, len(functions), 5):
    lines.append("            " + " ".join(f'"{n}",' for n in functions[i:i + 5]))
lines += ["        };", "    }", "}", ""]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
target = os.path.join(root, "modules", "WinapiModule.g.cs")
with open(target, "w", encoding="utf-8", newline="\n") as stream:
    stream.write("\n".join(lines))
print(target, len(constants), "constants,", len(texts), "str constants,", len(functions), "functions")
