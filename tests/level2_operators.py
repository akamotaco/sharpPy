# Arithmetic operators
print("=== Arithmetic ===")
a = 10 + 5
b = 10 - 5
c = 10 * 5
d = 10 / 5
e = 10 // 3
f = 10 % 3
g = 2 ** 3
print("10 + 5 =", a)
print("10 - 5 =", b)
print("10 * 5 =", c)
print("10 / 5 =", d)
print("10 // 3 =", e)
print("10 % 3 =", f)
print("2 ** 3 =", g)

# Comparison operators
print("\n=== Comparison ===")
print("5 == 5:", 5 == 5)
print("5 != 3:", 5 != 3)
print("5 > 3:", 5 > 3)
print("5 >= 5:", 5 >= 5)
print("3 < 5:", 3 < 5)
print("3 <= 3:", 3 <= 3)

# Logical operators
print("\n=== Logical ===")
print("True and False:", True and False)
print("True or False:", True or False)
print("not True:", not True)
print("not False:", not False)

# Bitwise operators
print("\n=== Bitwise ===")
print("5 & 3:", 5 & 3)
print("5 | 3:", 5 | 3)
print("5 ^ 3:", 5 ^ 3)
print("5 << 1:", 5 << 1)
print("5 >> 1:", 5 >> 1)
print("~5:", ~5)
