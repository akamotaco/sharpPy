# p41: bytes search/query argument protocol (find family, prefixes, buffer args).
# CPython Objects/bytesobject.c accepts an int byte 0..255, any bytes-like object
# (bytes / bytearray / memoryview), and tuples for startswith/endswith, with distinct
# error texts per case. Bytearray shares the same core (bytearrayobject.c delegates).
def s(label, fn):
    try:
        print(label, repr(fn()))
    except Exception as e:
        print(label, "EXC", type(e).__name__, str(e))


b = b"hello world"
s("find-int", lambda: b.find(119))
s("find-int-ff", lambda: b.find(255))
s("find-int-oob", lambda: b.find(300))
s("find-int-neg", lambda: b.find(-1))
s("find-ba", lambda: b.find(bytearray(b"wo")))
s("find-mv", lambda: b.find(memoryview(b"wo")))
s("find-str", lambda: b.find("o"))
s("find-range", lambda: b.find(b"o", 1, 4))
s("find-neg", lambda: b.find(b"o", 1, -3))
s("find-badstart", lambda: b.find(b"o", "x"))
s("find-None", lambda: b.find(b"o", None))
s("find-True", lambda: b.find(b"o", True))
s("rfind-int", lambda: b.rfind(108))
s("rfind-str", lambda: b.rfind("l"))
s("rfind-badstart", lambda: b.rfind(b"l", "x"))
s("count-int", lambda: b.count(108))
s("count-int-oob", lambda: b.count(300))
s("count-str", lambda: b.count("l"))
s("count-ba", lambda: b.count(bytearray(b"ll")))
s("count-mv", lambda: b.count(memoryview(b"ll")))
s("count-range", lambda: b.count(b"l", 3, 10))
s("count-badstart", lambda: b.count(b"l", "x"))
s("count-overlap", lambda: b"aaa".count(b"aa"))
s("index-int", lambda: b.index(119))
s("index-int-oob", lambda: b.index(300))
s("index-miss", lambda: b.index(b"zz"))
s("index-badstart", lambda: b.index(b"o", "x"))
s("rindex-int", lambda: b.rindex(108))
s("rindex-miss", lambda: b.rindex(b"zz"))
s("startswith", lambda: b.startswith(b"he"))
s("startswith-tuple", lambda: b.startswith((b"he", b"x")))
s("startswith-tuple-bad", lambda: b.startswith((b"a", "b")))
s("startswith-tuple-int", lambda: b.startswith((b"a", 1)))
s("startswith-empty-tuple", lambda: b.startswith(()))
s("startswith-ba", lambda: b.startswith(bytearray(b"he")))
s("startswith-mv", lambda: b.startswith(memoryview(b"he")))
s("startswith-int", lambda: b.startswith(104))
s("startswith-str", lambda: b.startswith("he"))
s("startswith-range", lambda: b.startswith(b"l", 2, 4))
s("startswith-neg", lambda: b.startswith(b"lo", -4))
s("endswith", lambda: b.endswith(b"ld"))
s("endswith-tuple", lambda: b.endswith((b"zz", b"ld")))
s("endswith-str", lambda: b.endswith("ld"))
s("endswith-int", lambda: b.endswith(100))
s("removeprefix", lambda: b.removeprefix(b"hello "))
s("removeprefix-none", lambda: b.removeprefix(b"zz"))
s("removeprefix-str", lambda: b.removeprefix("h"))
s("removeprefix-int", lambda: b.removeprefix(104))
s("removeprefix-2", lambda: b.removeprefix(b"a", b"b"))
s("removesuffix", lambda: b.removesuffix(b" world"))
s("removesuffix-str", lambda: b.removesuffix("d"))
s("count-0args", lambda: b.count())
s("find-0args", lambda: b.find())
s("find-4args", lambda: b.find(b"o", 1, 2, 3))
s("startswith-0args", lambda: b.startswith())

# Empty subsection matches at the range boundary.
s("empty-index", lambda: b"abc".index(b"", 1))
s("empty-rfind", lambda: b.rfind(b""))
s("empty-rfind-rng", lambda: b"abc".rfind(b"", 1))

# Same core must still serve bytearray.
ba = bytearray(b"hello world")
s("ba-find-mv", lambda: ba.find(memoryview(b"wo")))
s("ba-sv-mv", lambda: ba.startswith(memoryview(b"he")))
s("ba-rp-int", lambda: ba.removeprefix(104))
s("ba-rp-str", lambda: ba.removeprefix("h"))
s("ba-rp-2", lambda: ba.removeprefix(b"a", b"b"))
s("ba-rs", lambda: ba.removesuffix(b" world"))
