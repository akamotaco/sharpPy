# p13: format mini-language, sorted/min/max, dict/set methods (CPython 3.12)
def show(label, fn):
    try:
        print(label, repr(fn()))
    except BaseException as e:
        print(label, "EXC", type(e).__name__, str(e)[:90])

show("fmt.align", lambda: format("ab", ">10"))
show("fmt.fill", lambda: format("ab", "*^8"))
show("fmt.int", lambda: format(42, "08d"))
show("fmt.hex", lambda: format(255, "#x"))
show("fmt.float", lambda: format(3.14159, ".2f"))
show("fmt.pct", lambda: format(0.25, ".1%"))
show("fmt.comma", lambda: format(1234567, ","))
show("fmt.comma.f", lambda: format(1234567.891, ",.2f"))
show("fmt.exp", lambda: format(1234.5, "e"))
show("fmt.signed", lambda: (format(5, "+"), format(-5, "+"), format(5, " "), format(5, "-")))
show("fmt.nested", lambda: "{:>{w}}".format("x", w=6))
show("fmt.indexed", lambda: "{1}-{0}".format("a", "b"))
show("fmt.auto", lambda: "{}{}".format(1, 2))
show("fmt.mixed", lambda: "{0} {1}".format("a") if False else "{} {}".format(1, 2))
show("fmt.key", lambda: "{a[1]}-{a[x]}".format(a=[1,2]) if False else "{a[1]}".format(a=[9,8]))
show("fmt.attr", lambda: "{0.real}-{0.imag}".format(3j))
show("fmt.nospace", lambda: "{}".format(1.0))
show("fmt.bad.spec", lambda: format(5, "z"))
show("fmt.unterminated", lambda: format(5, "<"))
show("fmt.bad.nested", lambda: "{:{{}}}".format(1))
show("fmt.empty", lambda: "".format())
show("fmt.repr.spec", lambda: format(123, ">8"))
show("fmt.bytes.spec", lambda: format(b"ab", ">4"))
show("fmt.default", lambda: format(None))
show("fstr.width", lambda: (w := 7) and f"{'v':>{w}}")
show("fstr.dbl", lambda: f"{3.5:{10}.{3}}")
show("fmt.dollar", lambda: "{0:$^7}".format("x")) if False else None
show("fmt.custom.spec", lambda: format(type("Q", (), {"__format__": lambda s, spec: ("fmt", spec)})(), "sp"))

data = [3, 1, 2, 3, 1]
show("sorted.basic", lambda: sorted(data))
show("sorted.rev", lambda: sorted(data, reverse=True))
show("sorted.key", lambda: sorted(["bb", "a", "ccc"], key=len))
show("sorted.stable", lambda: sorted([(1, "b"), (0, "a"), (1, "c")]))
show("sorted.keynone.err", lambda: sorted([1, "a"]))
show("sorted.iter", lambda: sorted({"k": 2, "j": 1}))
show("sorted.gen", lambda: sorted(x for x in range(4)))
show("sorted.rev.kwonly", lambda: sorted([1], reverse="truthy"))
show("srt.key.kwonly", lambda: sorted([1, 2], key=None))
lst = list(data)
show("list.sort", lambda: (lst.sort(), lst)[1])
show("list.sort.rev", lambda: (lst.sort(reverse=True), lst)[1])
show("minmax", lambda: (min(3, 1, 2), max([4, 9])))
show("min.key", lambda: min(["aaa", "b"], key=len))
show("min.default", lambda: min([], default="d"))
show("min.empty", lambda: min([]))
show("min.iterable.kw", lambda: min(*[3, 1]))
show("max.keybad", lambda: max([1, "a"]))

d = {"a": 1}
show("dict.setdefault", lambda: (d.setdefault("b", 2), dict(d))[1])
show("dict.setdefault.pres", lambda: (d.setdefault("a", 99), d["a"])[1])
show("dict.pop", lambda: (d.pop("b"), dict(d))[1])
show("dict.pop.default", lambda: d.pop("zz", 7))
show("dict.pop.missing", lambda: d.pop("nope"))
show("dict.popitem", lambda: ({"x": 1, "y": 2}.popitem()))
show("dict.fromkeys", lambda: dict.fromkeys("abc", 0))
show("dict.fromkeys.none", lambda: dict.fromkeys([1, 2]))
show("dict.get.tuple", lambda: {}.get(("a", 1), "g"))
show("dict.update.kw", lambda: (lambda dd: (dd.update([("k", 1)], z=2), dd)[1])({}))
show("dict.clear.len", lambda: (lambda dd: (dd.clear(), len(dd))[1])({"q": 1}))
show("dict.eq.subset", lambda: {"a": 1} == {"a": 1, "b": 2})
show("dict.ne", lambda: {"a": 1} != {"a": 2})
show("dict.cmp.err", lambda: {"a": 1} < {"a": 2})
show("dict.key.type", lambda: (1, "x") in {1: "a"})
show("dict.hash.tuple", lambda: len({(1, 2): "ok"}))

s = {1, 2}
show("set.add", lambda: (s.add(3), sorted(s))[1])
show("set.discard", lambda: (s.discard(9), sorted(s))[1])
show("set.remove.miss", lambda: s.remove(99))
show("set.pop", lambda: len({5}.pop().__str__()) > 0)
show("set.update", lambda: sorted({1}.update([2, 3]) or {1})) if False else None
show("set.union.gen", lambda: sorted({1} | {2, 3}))
show("set.isdisjoint", lambda: {1}.isdisjoint({2}))
show("set.update.set", lambda: (lambda ss: (ss.update([3, 4]), sorted(ss))[1])({1, 2}))
show("set.ops.nonset", lambda: {1} | [2])
show("set.ror", lambda: [1] | {2})
show("frozen.hash", lambda: hash(frozenset([1, 2])) is not None)
show("set.repr", lambda: repr({1}) if False else "skip")
show("set.empty.repr", lambda: repr(set()))
show("set.iter.unique", lambda: len({1, 1.0, True}))
show("dict.key.dedup", lambda: len({1: "a", 1.0: "b", True: "c"}))
show("dict.lookup.float", lambda: {1: "v"}[True])
