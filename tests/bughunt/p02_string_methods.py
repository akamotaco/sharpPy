def show(label, fn):
    try:
        print(f"{label!r}: {fn()!r}")
    except BaseException as e:
        print(f"{label!r}: EXC {type(e).__name__}: {e}")

show("split.empty", lambda: "".split(","))
show("split.sep.space", lambda: "a  b".split(" "))
show("split.default", lambda: " a  b\tc\n".split())
show("split.maxsplit", lambda: "a,b,c,d".split(",", 1))
show("split.maxsplit.neg", lambda: "a,b,c,d".split(",", -1))
show("rsplit.default.maxsplit", lambda: "a b c d".rsplit(None, 2))
show("partition.missing", lambda: "abc".partition("z"))
show("rpartition.missing", lambda: "abc".rpartition("z"))
show("splitlines.keepends", lambda: "a\r\nb\rc\nd\r".splitlines(True))
show("splitlines.uni", lambda: "a\x0bb\x0cc\x1cd\x1ed\r\n".splitlines())
show("strip.char-set", lambda: "xyzabcxyz".strip("xyz"))
show("lstrip.none", lambda: "  a  ".lstrip())
show("remove_prefix_absent", lambda: "abc".removeprefix("z"))
show("casefold", lambda: ["Straße".casefold(), "İ".casefold("de") if False else "İ".casefold()])
show("swapcase", lambda: "ÄÖÜäöüΣσ".swapcase())
show("title", lambda: "it's a test-case 2nd".title())
show("capitalize", lambda: "hELLO wORLD".capitalize())
show("count.overlap", lambda: "aaa".count("aa"))
show("startswith.tuple", lambda: "abc".startswith(("x", "ab")))
show("startswith.pos", lambda: "abc".startswith("b", 1, 2))
show("find.args", lambda: ["abcabc".find("c", 3), "abcabc".find("c", 1, 3), "abc".find("d")])
show("index.missing", lambda: "abc".index("d"))
show("expandtabs", lambda: "a\tb".expandtabs(4) + "|" + "\t".expandtabs(0))
show("zfill.neg.width", lambda: "12".zfill(-3))
show("zfill.sign", lambda: "-12".zfill(5))
show("center.uneven", lambda: "ab".center(5, "-"))
show("format.auto", lambda: "{}-{}".format(1, 2))
show("format.mixed.auto", lambda: "{0}-{1}".format(1, 2) + "|" + "{}{0}".format(1, 2) if False else "{0}{}".format(1, 2))
show("format.spec", lambda: ["{:>5.2f}".format(3.14159), "{:0=+8d}".format(-42), "{:#x}".format(255), "{:,}".format(1234567)])
show("format.nested", lambda: "{0:{width}.{prec}f}".format(3.14159, width=8, prec=3))
show("format.dot.get", lambda: "{a.b!r}".format(a=type("T", (), {"b": [1]})()))
show("format.index", lambda: "{0[1]}{0[x]}".format([7]) if False else "{0[1]}".format([7]))
show("format.missing.key", lambda: "{k}".format())
show("format.unused", lambda: "{}".format(1, 2))
show("percent.tuple1", lambda: "%d" % (1,))
show("percent.mapping", lambda: "%(a)s-%(b)d" % {"a": "x", "b": 2})
show("percent.star", lambda: "%*d" % (5, 42))
show("percent.mod", lambda: "%.3s|%5.1f" % ("abcdef", 3.14159))
show("encode.errors", lambda: "é".encode("ascii", "replace"))
show("encode.unknown", lambda: "x".encode("no-such-codec"))
show("join.genexp", lambda: ",".join(str(i) for i in range(3)))
show("join.nonstr", lambda: ",".join([1, 2]))
show("maketrans.3arg", lambda: "abc".translate(str.maketrans("abc", "ABC", "b")))
show("repeat.neg", lambda: "ab" * -1)
show("mul.str.int", lambda: "3" * 3)
show("in.substr", lambda: ["" in "abc", "bc" in "abc", "" in ""])
show("fstring.eq", lambda: (lambda x: f"{x=}") (1 + 2))
show("fstring.nested.quotes", lambda: f"{'inner \\\"ok\\\"'}" if False else f"{'inner'}")
show("fstring.conversions", lambda: f"{3.5!r}|{3.5!s}|{[1]!a}")
show("fstring.spec.lambda", lambda: f"{(lambda: 42)():>4}")
show("fstring.backslash", lambda: f"a\\nb" if False else f"{'a\\nb'}")
