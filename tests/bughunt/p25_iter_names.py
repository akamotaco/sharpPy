# p25: iterator type names + repr (type(it).__name__, repr prefix).
# Addresses are volatile, so repr is checked by prefix, not exact address.
print("iter-list", type(iter([1, 2])).__name__)
print("iter-tuple", type(iter((1, 2))).__name__)
print("iter-str-ascii", type(iter("ab")).__name__)
print("iter-str-unicode", type(iter("\ud55c\uae00")).__name__)
print("iter-set", type(iter({1, 2})).__name__)
print("iter-frozenset", type(iter(frozenset({1, 2}))).__name__)
print("iter-dict", type(iter({1: 2})).__name__)
print("iter-dict-keys", type(iter({1: 2}.keys())).__name__)
print("iter-dict-values", type(iter({1: 2}.values())).__name__)
print("iter-dict-items", type(iter({1: 2}.items())).__name__)
print("iter-range", type(iter(range(3))).__name__)
print("iter-bytes", type(iter(b"ab")).__name__)
print("reversed-list", type(reversed([1, 2])).__name__)
print("reversed-range", type(reversed(range(3))).__name__)
print("reversed-dict", type(reversed({1: "a", 2: "b"})).__name__)
print("reversed-tuple", type(reversed((1, 2))).__name__)
print("reversed-str", type(reversed("ab")).__name__)
print("map", type(map(str, [1])).__name__)
print("filter", type(filter(None, [1])).__name__)
print("zip", type(zip([1], [2])).__name__)
print("enumerate", type(enumerate([1])).__name__)
print("gen", type((i for i in [1])).__name__)

print("repr-list", repr(iter([1, 2])).startswith("<list_iterator object at 0x"))
print("repr-range", repr(iter(range(3))).startswith("<range_iterator object at 0x"))
print("repr-reversed", repr(reversed([1, 2])).startswith("<list_reverseiterator object at 0x"))
print("repr-enumerate", repr(enumerate([1])).startswith("<enumerate object at 0x"))

print("type-identity", type(iter([1])) is type(iter([2])))
print("type-distinct", type(iter([1])) is not type(iter((1,))))
