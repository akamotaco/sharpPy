def show(label, fn):
    try:
        print(f"{label!r}: {fn()!r}")
    except BaseException as e:
        print(f"{label!r}: EXC {type(e).__name__}: {e}")

show("dict.order.mutate", lambda: (lambda d: (d.update({"b": 2, "a": 1}), list(d)))( {"x": 0}))
