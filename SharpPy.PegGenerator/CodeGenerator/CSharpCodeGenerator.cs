        private void GenerateParserMethods()
        {
            // Generate helper methods
            GenerateHelperMethods();

            // Generate methods for each rule
            foreach (var rule in _grammar.Rules)
            {
                GenerateRuleMethod(rule);
            }
        }

        private void GenerateHelperMethods()
